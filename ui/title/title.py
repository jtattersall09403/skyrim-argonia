"""The Argonia title (1.2 §a): a wordmark of our own, set in Pelagiad, with a reed-and-lozenge ornament.

This file is the title's one source. It writes the committed vector, `argonia-title.svg` (`--svg`), and at install
draws the same geometry with Pillow into the main menu's wallpaper texture, which replaces Dear Diary's Skyrim map
and "Skyrim" wordmark (textures/interface/objects/mainmenuwallpaper.dds, 2048 x 2048, shown through Dear Diary's
meshes/interface/logo/logo.nif). The DDS is a derived file and is made on the player's machine (0014).

No Nordic motif (0006): no knotwork, no dragon, no horn, no runic angle. The ornament is a hairline with a lozenge
between two reed leaves, the marsh's plant.
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
SVG = HERE / "argonia-title.svg"

# The title block, in its own units (1 unit = 1 px at the wallpaper's scale).
W, H = 760, 300
WORD = "ARGONIA"
WORD_SIZE, WORD_BASE, WORD_TRACK = 150, 190, 0.08  # size, baseline y, letter spacing in em
OVER = "ELDER SOULS"
OVER_SIZE, OVER_BASE, OVER_TRACK = 40, 62, 0.30
RULE_Y, RULE_HALF = 84, 210  # the hairline under the over-line
ORN_Y, ORN_HALF = 226, 300  # the ornament's line under the wordmark
LOZ_W, LOZ_H = 22, 13  # the lozenge's half width and half height
LEAF_LEN, LEAF_W = 64, 9  # each reed leaf beside the lozenge
STROKE = 3

# Where the block sits on the 2048 wallpaper: Dear Diary's wordmark box, measured 2026-10-30 (x 643-1348,
# y 651-831), and its lit band (rows 509-1279, columns 0-1991).
WALL = 2048
BLOCK_CX, BLOCK_TOP = 995, 515
BAND_TOP, BAND_BOTTOM, BAND_RIGHT, FEATHER = 509, 1279, 1991, 110


def leaf(cx: float, cy: float, direction: int, n: int = 16) -> list[tuple[float, float]]:
    """A reed leaf: a long lens from the lozenge's tip outward, its belly a sine."""
    x0 = cx + direction * (LOZ_W + 6)
    pts = [(x0 + direction * LEAF_LEN * k / n, cy - LEAF_W * math.sin(math.pi * k / n)) for k in range(n + 1)]
    pts += [(x0 + direction * LEAF_LEN * k / n, cy + LEAF_W * 0.35 * math.sin(math.pi * k / n)) for k in range(n, -1, -1)]
    return pts


def ornament_shapes(cx: float) -> dict:
    loz = [(cx, ORN_Y - LOZ_H), (cx + LOZ_W, ORN_Y), (cx, ORN_Y + LOZ_H), (cx - LOZ_W, ORN_Y)]
    gap = LOZ_W + 6 + LEAF_LEN + 8
    return {
        "lines": [((cx - ORN_HALF, ORN_Y), (cx - gap, ORN_Y)), ((cx + gap, ORN_Y), (cx + ORN_HALF, ORN_Y)),
                  ((cx - RULE_HALF, RULE_Y), (cx + RULE_HALF, RULE_Y))],
        "lozenge": loz,
        "leaves": [leaf(cx, ORN_Y, -1), leaf(cx, ORN_Y, 1)],
        "dots": [(cx - ORN_HALF - 10, ORN_Y), (cx + ORN_HALF + 10, ORN_Y)],
    }


def svg() -> str:
    cx = W / 2
    o = ornament_shapes(cx)

    def pts(p):
        return " ".join(f"{x:.1f},{y:.1f}" for x, y in p)

    rows = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">',
        "  <!-- Argonia's title, generated by ui/title/title.py (the source); Pelagiad, OFL -->",
        '  <g fill="#f1e8cf" font-family="Pelagiad, Palatino, serif" text-anchor="middle">',
        f'    <text x="{cx}" y="{OVER_BASE}" font-size="{OVER_SIZE}" letter-spacing="{OVER_TRACK * OVER_SIZE:.1f}"'
        f' fill="#e6d9b8">{OVER}</text>',
        f'    <text x="{cx}" y="{WORD_BASE}" font-size="{WORD_SIZE}" letter-spacing="{WORD_TRACK * WORD_SIZE:.1f}"'
        f">{WORD}</text>",
        "  </g>",
        f'  <g stroke="#cdbb8f" stroke-width="{STROKE}" fill="none" stroke-linecap="round">',
    ]
    rows += [f'    <line x1="{a[0]:.1f}" y1="{a[1]}" x2="{b[0]:.1f}" y2="{b[1]}"/>' for a, b in o["lines"]]
    rows += ["  </g>", '  <g fill="#cdbb8f">', f'    <polygon points="{pts(o["lozenge"])}" fill="#b0702a"/>']
    rows += [f'    <polygon points="{pts(lf)}"/>' for lf in o["leaves"]]
    rows += [f'    <circle cx="{x:.1f}" cy="{y}" r="4"/>' for x, y in o["dots"]]
    rows += ["  </g>", "</svg>", ""]
    return "\n".join(rows)


def _tracked(draw: ImageDraw.ImageDraw, text: str, font, cx: float, base: float, track: float, size: int, fill):
    widths = [font.getlength(ch) for ch in text]
    total = sum(widths) + track * size * (len(text) - 1)
    x = cx - total / 2
    for ch, w in zip(text, widths):
        draw.text((x, base), ch, font=font, fill=fill, anchor="ls")
        x += w + track * size


def block(ttf: Path, scale: int = 3) -> Image.Image:
    """The title block as RGBA, drawn at `scale` times and reduced (Pillow's antialiasing for the ornament)."""
    s = scale
    img = Image.new("RGBA", (W * s, H * s), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    cx = W / 2
    _tracked(d, OVER, ImageFont.truetype(str(ttf), OVER_SIZE * s), cx * s, OVER_BASE * s, OVER_TRACK, OVER_SIZE * s,
             (230, 217, 184, 255))
    _tracked(d, WORD, ImageFont.truetype(str(ttf), WORD_SIZE * s), cx * s, WORD_BASE * s, WORD_TRACK, WORD_SIZE * s,
             (241, 232, 207, 255))
    o = ornament_shapes(cx)
    trim, amber = (205, 187, 143, 255), (176, 112, 42, 255)
    for a, b in o["lines"]:
        d.line([(a[0] * s, a[1] * s), (b[0] * s, b[1] * s)], fill=trim, width=STROKE * s)
    for lf in o["leaves"]:
        d.polygon([(x * s, y * s) for x, y in lf], fill=trim)
    d.polygon([(x * s, y * s) for x, y in o["lozenge"]], fill=amber)
    for x, y in o["dots"]:
        d.ellipse([(x - 4) * s, (y - 4) * s, (x + 4) * s, (y + 4) * s], fill=trim)
    return img.resize((W, H), Image.Resampling.LANCZOS)


def paper(size: int, seed: int = 1847) -> np.ndarray:
    """A soft mottle in 0..1: octaves of smoothed value noise, our own (no source image)."""
    rng = np.random.default_rng(seed)
    acc = np.zeros((size, size), np.float32)
    amp, total = 1.0, 0.0
    for cells in (4, 8, 16, 32, 64, 128):
        grid = Image.fromarray((rng.random((cells, cells)) * 255).astype(np.uint8))
        acc += amp * np.asarray(grid.resize((size, size), Image.Resampling.BICUBIC), np.float32) / 255
        total += amp
        amp *= 0.6
    acc /= total
    return (acc - acc.min()) / max(float(acc.max() - acc.min()), 1e-6)


def wallpaper(ttf: Path, palette) -> Image.Image:
    """The 2048 main-menu wallpaper: our dark paper band, feathered to black, with the title on it."""
    n = paper(WALL)
    lum = 0.16 + 0.22 * n  # a dark sheet, as Dear Diary's lit map is (mean RGB 113, 83, 60)
    rgb = palette.tone(lum)
    y = np.arange(WALL, dtype=np.float32)[:, None]
    x = np.arange(WALL, dtype=np.float32)[None, :]

    def ramp(v):
        v = np.clip(v, 0, 1)
        return v * v * (3 - 2 * v)

    env = ramp((y - BAND_TOP) / FEATHER) * ramp((BAND_BOTTOM - y) / FEATHER) * ramp((BAND_RIGHT - x) / FEATHER)
    cy = (BAND_TOP + BAND_BOTTOM) / 2
    glow = 1 - 0.35 * np.clip(((x - BLOCK_CX) / 1100) ** 2 + ((y - cy) / 420) ** 2, 0, 1)  # lit at the title
    img = np.clip(rgb * (env * glow)[..., None] * 255, 0, 255).astype(np.uint8)
    out = Image.fromarray(img, "RGB").convert("RGBA")
    out.alpha_composite(block(ttf), (BLOCK_CX - W // 2, BLOCK_TOP))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--svg", action="store_true", help="rewrite argonia-title.svg from this file")
    ap.add_argument("--png", type=Path, help="write the title block as PNG (needs --ttf)")
    ap.add_argument("--ttf", type=Path)
    a = ap.parse_args(argv)
    if a.svg:
        SVG.write_text(svg())
        print(SVG)
    if a.png:
        block(a.ttf).save(a.png)
        print(a.png)
    return 0


if __name__ == "__main__":
    sys.exit(main())
