        var tiltsRef = k.Actor("ARG_TG_TiltsRef", tilts, tiltsAt, null);
        var stabiRef = k.Actor("ARG_TG_STabiRef", stabi, stabiAt, null);
        var thiefRef = k.Actor("ARG_TG_KeepsWhatFloatsRef", thief, dayAt, p1);
        var friendRef = k.Actor("ARG_TG_SitsByTheWaterRef", friend, friendAt, p1);
        var bentRef = k.Actor("ARG_TG_BentSpineRef", bent, bentAt, p1);
        var look1Ref = k.Actor("ARG_TG_ChapterLookout1Ref", look1, look1At, p1);
        var look2Ref = k.Actor("ARG_TG_ChapterLookout2Ref", look2, look2At, p1);
        var neetaRef = k.Actor("ARG_TG_NeetaHajRef", neeta, neetaAt, p2);
        var okanRef = k.Actor("ARG_TG_OkanTeiRef", okan, okanAt, p2);
        var darRef = k.Actor("ARG_TG_DarZeelRef", dar, darAt, p2);
