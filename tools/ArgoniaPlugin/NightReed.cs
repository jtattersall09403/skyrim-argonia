        var sleepAt = k.Snap(SoulrestNav, 49856, -6784);            // under the shacks' eaves north-west of the house
        var bentAt = k.Snap(ChapterRoom, 1500, 2000);              // the inner room, past the ladder's corridor
        var look1At = k.Snap(ChapterRoom, 1900, 2600);
