        var bankAt = k.Snap(BankNav, 23050, 650);                  // TG02's clients on the channel's south bank
        var neetaAt = k.Snap(BankNav, 23100, 500);
        var okanAt = k.Snap(BankNav, 23300, 700);
        var darAt = k.Snap(BankNav, 23500, 520);
