#!/usr/bin/env python3
"""docs/INDEX.md: every document under docs/ and world/sources/lore/ (and world/IMPORTED_FROM.md), one line each.

Purpose rule: a `purpose:` line if the file has one, else the first heading, then the first sentence of the first
prose paragraph; cut so the whole line is about 120 characters (40 minimum). A wrong purpose is fixed at the document's first line, not here.
    doc_index.py --write   rebuild docs/INDEX.md
    doc_index.py --check   exit 1 when it is stale (a doc added, removed, or its first line changed)
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = "docs/INDEX.md"
ROOTS = ("docs", "world/sources/lore")
EXTRA = ("world/IMPORTED_FROM.md",)
MAX = 120


def _clean(s):
    s = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", s)  # links to their text
    s = re.sub(r"[*_`]", "", s)
    return " ".join(s.split())


def purpose(text, limit=MAX):
    """The one-line purpose of a markdown document's text."""
    lines = text.splitlines()
    for ln in lines:
        m = re.match(r"\s*purpose:\s*(.+)", ln, re.I)
        if m:
            return _clean(m.group(1))[:limit]
    if lines and lines[0].strip() == "---":  # front matter
        end = next((i for i, ln in enumerate(lines[1:], 1) if ln.strip() == "---"), 0)
        lines = lines[end + 1:]
    head, i = "", 0
    for i, ln in enumerate(lines):
        if ln.startswith("#"):
            head = _clean(ln.lstrip("#"))
            break
    else:
        i = -1
    para = []
    for ln in lines[i + 1:]:
        s = ln.strip()
        if not s:
            if para:
                break
            continue
        if s.startswith(("#", "|", ">", "```", "---", "- ", "* ")) or re.match(r"\*\*[^*]+:\*\*", s):
            if para:
                break
            continue
        para.append(s)
    body = _clean(" ".join(para))
    m = re.match(r".*?[.!?](?=\s|$)", body)
    sent = m.group(0) if m else body
    out = f"{head} — {sent}" if head and sent else head or sent
    if len(out) > limit:
        out = out[:limit - 1].rstrip() + "…"
    return out


def docs():
    found = set(EXTRA)
    for r in ROOTS:
        found.update(str(p.relative_to(ROOT)) for p in (ROOT / r).rglob("*.md"))
    found.discard(OUT)
    return sorted(p for p in found if (ROOT / p).is_file())


def build():
    groups = defaultdict(list)
    for p in docs():
        groups[str(Path(p).parent)].append(p)
    out = ["# Document index", "",
           "Generated by `python3 tools/doc_index.py --write`; do not edit. Every document under `docs/`,",
           "`world/sources/lore/` and `world/IMPORTED_FROM.md`, one line each. Say \"not in the repo\" only after",
           "reading this and `world/IMPORTED_FROM.md`. A wrong purpose is fixed at the document's first line.", ""]
    for d in sorted(groups):
        out += [f"## {d} ({len(groups[d])})", ""]
        out += [f"- {p} — {purpose((ROOT / p).read_text(errors='replace'), max(40, MAX - len(p) - 5))}" for p in groups[d]]
        out.append("")
    return "\n".join(out)


def main(argv):
    text = build()
    f = ROOT / OUT
    if "--write" in argv:
        f.write_text(text)
        print(f"{OUT}: {len(docs())} documents")
        return 0
    if "--check" in argv:
        if f.exists() and f.read_text() == text:
            return 0
        print(f"{OUT} is stale: run python3 tools/doc_index.py --write")
        return 1
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
