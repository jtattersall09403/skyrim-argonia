"""A quest thing's native hook (1.4): activating its activator, or reading its book, sets one flag of the quest.

The rows are `thing_hook` (quest, thing, hook, flag). Each thing is placed as a record (its `build_ref` base), and
ArgoniaCore's thing table is keyed by that record's world id (its `formid` entity key), so the adapter goes from the
activated reference's base form to the flag with no editor id at run time:

- **activate**: the thing's ACTI carries the keyword `ARG_ThingHook`; the hidden player perk `ARG_Perk_ThingHooks`
  has an Activate entry (Run Immediately, Replace Default, "Examine") on that keyword, whose fragment
  (ARG_PRKF_ThingHook.psc) makes one native call, `ArgoniaCore.ThingActivated(akTargetRef)`. The pattern of the rest
  intercept and the closed road; ArgoniaCore's EnsurePerks gives the perk by its world id.
- **read**: the Book Menu opening on the book (ArgoniaCore's menu sink reads BookMenu's target form). No Papyrus.

ArgoniaCore then sets the flag (the `setFlag` action), so the quest runtime completes the clue and the journal
notice follows. The table is rendered into skse/core/generated/argonia/core/things_table.h by core_tables.py.

    python3 -m tools.argonia_world.thing_hooks       every hook resolved to its record, or why not
"""
from __future__ import annotations

import sys

from tools.argonia_world.core_tables import OUT, sv  # noqa: F401 (OUT: where things_table.h is written)

KEYWORD = ("ARG_ThingHook", "hook.thing")
PERK = ("ARG_Perk_ThingHooks", "hook.thing-activate")  # ArgoniaCore's EnsurePerks gives it by this world id
FRAGMENT_SCRIPT = "ARG_PRKF_ThingHook"
VERB = "Examine"
HEADER = "things_table.h"


def hooks(w) -> tuple[list[tuple[str, str, str, str, str]], list[str]]:
    """(record world id, record EditorID, hook, flag, quest) per thing_hook row, sorted by record id, and why each
    other row resolves to nothing."""
    out, bad = [], []
    for h in w.rows("thing_hook"):
        at = f"thing_hook {h.quest_id} {h.thing_id}"
        if not w.query("SELECT 1 FROM quest_thing WHERE quest_id = ? AND id = ?", h.quest_id, h.thing_id):
            bad.append(f"{at}: the quest has no such thing")
            continue
        if not w.query("SELECT 1 FROM quest_touch WHERE quest_id = ? AND id = ? AND access = 'write'",
                       h.quest_id, h.sets_flag):
            bad.append(f"{at}: the quest does not write {h.sets_flag} (quest_touch)")
            continue
        bases = sorted({r["base"] for r in w.query("SELECT base FROM build_ref WHERE thing_id = ?", h.thing_id)})
        if len(bases) != 1:
            bad.append(f"{at}: placed as {len(bases)} records ({', '.join(bases) or 'none'}), wanted one")
            continue
        f = w.query("SELECT entity_key, record_type FROM formid WHERE editor_id = ? AND plugin = 'Argonia.esm'",
                    bases[0])
        want = "ACTI" if h.hook == "activate" else "BOOK"
        if not f or not f[0]["entity_key"]:
            bad.append(f"{at}: {bases[0]} has no formid row with a world id")
        elif f[0]["record_type"] != want:
            bad.append(f"{at}: {bases[0]} is a {f[0]['record_type']}, a {h.hook} hook needs a {want}")
        else:
            out.append((f[0]["entity_key"], bases[0], h.hook, h.sets_flag, h.quest_id))
    out.sort()
    return out, bad


def activated(w) -> set[str]:
    """The EditorIDs of the activators that carry the hook keyword."""
    return {e for _, e, hook, *_ in hooks(w)[0] if hook == "activate"}


def records(alloc) -> list[dict]:
    """The keyword and the hidden perk whose Activate entry calls ArgoniaCore.ThingActivated."""
    kw = alloc.form_key(KEYWORD[0], "KYWD", KEYWORD[1])
    return [
        {"type": "KYWD", "edid": KEYWORD[0], "formKey": kw},
        {"type": "PERK", "edid": PERK[0], "formKey": alloc.form_key(PERK[0], "PERK", PERK[1]), "hidden": True,
         "playable": False, "trait": False, "level": 0, "ranks": 1, "name": "", "description": "",
         "effects": [{"entryPoint": "Activate", "function": "AddActivateChoice", "rank": 0, "priority": 0,
                      "tabCount": 2,
                      "conditions": [{"tab": 1, "function": "HasKeyword", "keyword": kw, "op": "EqualTo", "value": 1}],
                      "buttonLabel": VERB, "flags": ["RunImmediately", "ReplaceDefault"], "fragment": 0}],
         "fragments": {"script": FRAGMENT_SCRIPT, "entries": [{"index": 0, "name": "Fragment_0"}]}},
    ]


def layer(alloc, w):
    from tools.argonia_world.intermediate import Layer
    return Layer("base:thing-hooks", records(alloc) if hooks(w)[0] else [])


def render(w) -> str:
    """things_table.h: the thing table, by record world id."""
    rows, bad = hooks(w)
    if bad:
        raise ValueError("thing_hooks: " + "; ".join(bad))
    b = ["// things_table.h: GENERATED by tools/argonia_world/thing_hooks.py (via core_tables.py) from the thing_hook table",
         "// (1.4). Data only. Do not edit: `python3 -m tools.argonia_world.core_tables`.",
         "#pragma once", "#include <array>", "#include <string_view>", "",
         "namespace argonia::core::gen {", "",
         "// A quest thing's hook: the world id of the record it is placed as, how the player meets it (activate, read),",
         "// the flag that sets and the quest that owns it. Sorted by record.",
         "struct ThingHookRow { std::string_view record, hook, flag, quest; };",
         f"inline constexpr std::array<ThingHookRow, {len(rows)}> kThingHooks{{{{"]
    b += [f"    {{{sv(r)}, {sv(h)}, {sv(f)}, {sv(q)}}}," for r, _, h, f, q in rows]
    b += ["}};", "", "}  // namespace argonia::core::gen", ""]
    return "\n".join(b)


def main() -> int:
    from tools.argonia_world import db
    rows, bad = hooks(db.open())
    for r in rows:
        print(f"{r[2]:8} {r[1]} ({r[0]}) -> {r[3]}  [{r[4]}]")
    for x in bad:
        print("NOT RESOLVED:", x)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
