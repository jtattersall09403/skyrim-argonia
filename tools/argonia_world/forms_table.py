"""The world id -> FormID table ArgoniaCore resolves records by (1.1 adapters; decision 0030).

ArgoniaCore's adapters name records by world id (``item.lf83.clay-basket``, ``npc.…``, ``quest.local.lf83``), as the
conditions, actions and co-save keys do. Skyrim names them by FormID, and keeps few editor ids at run time. This
renders the db's ``formid`` rows that carry an entity key into skse/core/generated/argonia/core/forms.h, sorted by
id, so the plugin resolves both ways (``TESDataHandler::LookupForm(local, plugin)`` and back) with no sidecar file.
A part row (``item.steel-boots#boots``, the ARMA of an ARMO) is left out: the adapters only name whole records.

Rendered by ``core_tables.py`` (so ``core_tables --check`` in skse/check.sh refuses a stale table) and written by
``make plugin`` right after the allocator saves new rows (tools/ArgoniaGen/pipeline.py), so a lane that adds records
regenerates it with the plugin.

    python3 -m tools.argonia_world.forms_table      # write forms.h only
"""
from __future__ import annotations

import sys

from tools.argonia_world import db
from tools.argonia_world.core_tables import OUT, sv

HEADER = "forms.h"


def rows(w: db.World) -> list[tuple[str, str, str, int]]:
    """(entity key, plugin, record type, local FormID) of every whole record with a world id, by id."""
    out = [(r.entity_key, r.plugin, r.record_type or "", int(r.form_id)) for r in w.rows("formid")
           if r.entity_key and "#" not in r.entity_key]
    out.sort()
    dup = sorted({k for k, *_ in out if sum(1 for o in out if o[0] == k) > 1})
    if dup:
        raise ValueError(f"forms_table: one world id names two records: {', '.join(dup)}")
    return out


def render(w: db.World) -> str:
    rs = rows(w)
    b = ["// forms.h: GENERATED by tools/argonia_world/forms_table.py (via core_tables.py) from the formid table",
         "// (decision 0030). Data only. Do not edit: `make plugin` or `python3 -m tools.argonia_world.forms_table`.",
         "#pragma once", "#include <array>", "#include <cstdint>", "#include <string_view>", "",
         "namespace argonia::core::gen {", "",
         "// One record of ours by its world id: the plugin that holds it, its signature and its local FormID.",
         "struct FormRow { std::string_view id, plugin, type; std::uint32_t local; };",
         f"inline constexpr std::array<FormRow, {len(rs)}> kForms{{{{"]
    b += [f"    {{{sv(k)}, {sv(p)}, {sv(t)}, 0x{f:06X}}}," for k, p, t, f in rs]
    b += ["}};", "", "}  // namespace argonia::core::gen", ""]
    return "\n".join(b)


def write() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / HEADER).write_text(render(db.open()), encoding="utf-8")


def main() -> int:
    write()
    print(f"forms_table: wrote {HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
