"""tests/journeys/creature-spots.yaml and tests/scenes/creature-spots.txt from a planner run (1.15 §g.4).

Journeys stay simple (owner, 2026-11-01): the mods' creatures are checked as placed, never walked to or fought.
Six spawn points of three habitats (water, marsh, upland), two of each in different cells, one visited by day and
one by night: teleport beside the point, wait, read the actors loaded within READ_M (base form and distance: the
bridge's `actors`; the kind is the base's creature_form row) and take one still. Then one teleport to a predator
den (the run's first den) with a still. No walking, no fighting.

    python3 -m tools.argonia_world.creatures journey [--out out/creatures]
"""
from __future__ import annotations

import json
from pathlib import Path

from tools.argonia_world import skyrim_units as su

ROOT = Path(__file__).resolve().parents[3]
HABITATS = {  # name -> (media, region classes)
    "water": (("water", "shore"), None),
    "marsh": (("land",), ("deep-sink-basin", "interior-swamp", "flooded-forest", "rootland")),
    "upland": (("land",), ("western-frontier", "northern-transition")),
}
HOURS = (("day", 13), ("night", 1))
READ_M = 40.0
VIEW_M = 8.0  # the player stands this far west of the point, facing it (east)
DEN_VIEW_M = 12.0
WAIT_S = 6


def spots(refs: list[dict]) -> list[tuple[str, str, int, dict]]:
    out = []
    for name, (media, classes) in HABITATS.items():
        pts = [r for r in refs if r["kind"] == "spawn" and r["medium"] in media
               and (classes is None or r["class"] in classes)]
        cells: list = []
        for r in sorted(pts, key=lambda r: (r["cell"], r["x"], r["y"])):
            if tuple(r["cell"]) not in [tuple(c["cell"]) for c in cells]:
                cells.append(r)
        for (when, hour), r in zip(HOURS, cells[:2]):
            out.append((name, when, hour, r))
    return out


LIFT = 800  # units above the generated ground the player is put (god mode: the engine drops him to the ground)


def ground_z(ground, x: float, y: float) -> float:
    """The generated ground's height (units) at a Skyrim position: nearest sample of the ground-f32.npy."""
    xm, ym = su.skyrim_to_province(x, y)
    n = ground.shape[0] - 1
    col = min(max(round(xm / su.PROVINCE_SAMPLE_M), 0), n)
    row = min(max(round(ym / su.PROVINCE_SAMPLE_M), 0), n)
    return float(ground[row, col]) * su.UNITS_PER_METRE


def _target(r: dict, off_m: float, ground) -> tuple[float, float, float]:
    x, y = r["x"] - off_m * su.UNITS_PER_METRE, r["y"]
    z = ground_z(ground, x, y) + LIFT if ground is not None else r["z"] + LIFT
    return x, y, z


def _go(r: dict, off_m: float, hour: int, ground=None) -> list[str]:
    cx, cy = r["cell"]
    x, y, z = _target(r, off_m, ground)
    return [f"  - console: {{line: cow ARG_Province {cx} {cy}, settle: 60}}",
            "  - wait: 8",
            f"  - console: set gamehour to {hour}",
            f"  - console: player.setpos x {x:.0f}",
            f"  - console: player.setpos y {y:.0f}",
            f"  - console: player.setpos z {z:.0f}",
            "  - camera: first",
            "  - console: player.setangle z 90",
            f"  - wait: {WAIT_S}"]


def build(refs: list[dict], ground=None) -> tuple[str, str]:
    radius = READ_M * su.UNITS_PER_METRE
    lines = ["# Creature spots (1.15 §g.4), generated by `python3 -m tools.argonia_world.creatures journey`: six",
             "# spawn points (water, marsh, upland; three by day, three by night) and one predator den, each reached",
             "# by teleport, then a wait, a read of the actors within 40 m and one still. No walking, no fighting",
             "# (owner, 2026-11-01). Fails when no actor stands within 40 m of a point (a list with chance none 0",
             "# and every entry at level 1 always yields one). Reader checklist per still: the creature is a Black",
             "# Marsh kind (no Skyrim animal), on ground or in water its kind allows; at the den the predator beside",
             "# it. The kind of each base read is its creature_form row. The planner runs it in the round's batch.",
             "id: creature-spots", "runner: 1", "crash_risk: medium", "scene: creature-spots", "steps:"]
    for n, (name, when, hour, r) in enumerate(spots(refs)):
        lines += [f"- name: {name}-{when}",
                  f"  # cell {tuple(r['cell'])} {r['class']} {r['band']} {r['medium']}: list {r['base']}",
                  "  do:", *(["  - hud: off", "  - console: tgm"] if n == 0 else []), *_go(r, VIEW_M, hour, ground),
                  "  expect:", "  - {read: [player], path: pos, keep: arrive}",
                  f"  - {{read: [actors, \"{radius:.0f}\"], path: listed, keep: {name}_{when}}}"]
    den = next((r for r in refs if r["kind"] == "den"), None)
    if den is not None:
        lines += [f"- name: den-{den['creature'].split('.')[-1]}",
                  f"  # {den['creature']} den in cell {tuple(den['cell'])}, {den['class']} {den['band']}",
                  "  do:", *_go(den, DEN_VIEW_M, 12, ground),
                  "  expect:", "  - {read: [player], path: pos, keep: arrive}",
                  f"  - {{read: [actors, \"{radius:.0f}\"], path: listed, keep: den}}"]
    scene = ("; Creature spots (1.15 §g.4): god mode so a bite does not end the visit; sets nothing it tests\n"
             "tgm\nfw ARG_Weather_tannin_haze\n")
    return "\n".join(lines) + "\n", scene


def write(out: Path) -> tuple[Path, Path]:
    """Plan the 1.15 sample on the newest frozen ground (the one the next plugin build uses) and write both files."""
    import numpy as np
    from tools.argonia_world import db
    from tools.argonia_world.creatures import build as cb
    from tools.argonia_world.terrain.grid import Sources
    from tools.argonia_world.terrain.world import SAMPLE_1_15
    from tools.argonia_world.water import solve
    g = sorted((ROOT / "out" / "terrain" / "build").glob("*/ground-f32.npy"), key=lambda p: p.stat().st_mtime)[-1]
    w = db.open()
    run = cb.run(w, Sources.load(ground=g), solve.load(w), cb.sample_cells(SAMPLE_1_15), None, log=lambda s: None,
                 veg=ROOT / "out" / "terrain" / "vegetation")
    y, s = build(run["refs"], np.load(g, mmap_mode="r"))
    jp, sp = ROOT / "tests" / "journeys" / "creature-spots.yaml", ROOT / "tests" / "scenes" / "creature-spots.txt"
    jp.write_text(y)
    sp.write_text(s)
    return jp, sp


if __name__ == "__main__":
    print(write(ROOT / "out" / "creatures"))
