"""tests/journeys/creature-walk.yaml and tests/scenes/creature-walk.txt from a planner run (1.15 §g.4).

Three stretches of the 1.15 sample (the marsh, river and upland cells holding the most spawn refs of their
classes), each walked at day and at night from a fixed start: teleport to the cell's start, face its spawns, walk
forward, read the actors near and the hits taken (state and events; a still per step). Then one still per big
predator at its den (the first den of each den creature in the run), from DEN_VIEW_M away.

    python3 -m tools.argonia_world.creatures journey [--out out/creatures]
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from tools.argonia_world import skyrim_units as su

ROOT = Path(__file__).resolve().parents[3]
STRETCHES = {"marsh": ("deep-sink-basin", "interior-swamp"), "river": ("flooded-forest", "deep-river-corridor"),
             "upland": ("western-frontier", "northern-transition")}
HOURS = {"day": 13, "night": 1}
DEN_VIEW_M = 12.0
WALK_MS = 2900  # the runner's input cap is 3000 ms: three pushes make the walk


def _cell_start(cx: int, cy: int) -> tuple[float, float]:
    return cx * su.CELL_UNITS + su.CELL_UNITS / 2, cy * su.CELL_UNITS + su.CELL_UNITS / 2


def build(refs: list[dict]) -> tuple[str, str]:
    lines = ["# Creature walk (1.15 §g.4), generated by `python3 -m tools.argonia_world.creatures journey`: three",
             "# stretches walked at day and night, reading the actors near and what attacked; a still per step;",
             "# then a still per big predator at its den. Reader checklist per still: creatures in view are Black Marsh",
             "# kinds (no Skyrim animal), on ground or in water their kind allows, none inside a settlement; at a den",
             "# the predator stands beside it. The planner runs it in the round's batch; never set what it tests.",
             "id: creature-walk", "runner: 1", "crash_risk: medium", "scene: creature-walk", "steps:"]
    for name, classes in STRETCHES.items():
        cells = Counter(tuple(r["cell"]) for r in refs if r["class"] in classes and r["kind"] == "spawn")
        if not cells:
            continue
        (cx, cy), n = cells.most_common(1)[0]
        x, y = _cell_start(cx, cy)
        for when, hour in HOURS.items():
            lines += [f"- name: {name}-{when}",
                      f"  # cell ({cx},{cy}) {classes[0]}: {n} spawn refs planned",
                      "  do:",
                      f"  - console: {{line: cow ARG_Province {cx} {cy}, settle: 60}}",
                      "  - wait: 8",
                      f"  - console: set gamehour to {hour}",
                      f"  - console: player.setpos x {x:.0f}",
                      f"  - console: player.setpos y {y:.0f}",
                      "  - wait: 2",
                      *[f"  - pad: +LY=1:{WALK_MS} -:100"] * 3,
                      "  - wait: 4",
                      "  expect:",
                      "  - {read: [actors, \"6000\"], path: listed, keep: seen_" + f"{name}_{when}" + "}"]
    seen = set()
    for r in refs:
        if r["kind"] != "den" or r["creature"] in seen:
            continue
        seen.add(r["creature"])
        cx, cy = r["cell"]
        off = DEN_VIEW_M * su.UNITS_PER_METRE
        lines += [f"- name: den-{r['creature'].split('.')[-1]}",
                  f"  # {r['creature']} den in cell ({cx},{cy}), {r['class']} {r['band']}, {r['medium']}",
                  "  do:",
                  f"  - console: {{line: cow ARG_Province {cx} {cy}, settle: 60}}",
                  "  - wait: 8",
                  "  - console: set gamehour to 12",
                  f"  - console: player.setpos x {r['x'] - off:.0f}",
                  f"  - console: player.setpos y {r['y']:.0f}",
                  f"  - console: player.setpos z {r['z'] + 200:.0f}",
                  "  - console: player.setangle z 90",
                  "  - console: tcai",
                  "  - wait: 4",
                  "  - console: tcai",
                  "  expect:",
                  "  - {read: [actors, \"2000\"], path: listed, keep: den_" + r["creature"].split(".")[-1].replace("-", "_") + "}"]
    scene = ("; Creature walk (1.15 §g.4): god mode so a bite does not end the walk; sets nothing it tests\n"
             "tgm\nfw ARG_Weather_tannin_haze\n")
    return "\n".join(lines) + "\n", scene


def write(out: Path) -> tuple[Path, Path]:
    refs = [json.loads(x) for x in (out / "spawns.jsonl").read_text().splitlines() if x]
    y, s = build(refs)
    jp, sp = ROOT / "tests" / "journeys" / "creature-walk.yaml", ROOT / "tests" / "scenes" / "creature-walk.txt"
    jp.write_text(y)
    sp.write_text(s)
    return jp, sp


if __name__ == "__main__":
    print(write(ROOT / "out" / "creatures"))
