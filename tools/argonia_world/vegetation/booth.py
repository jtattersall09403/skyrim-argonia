"""The rock booth (1.15 §e.2): six of our placed rocks, one still each from a fixed vantage, so a reader can judge
"sunk, no gap, no hollow back" and the ConformToSlope sign. Generated from the placer's shards (never hand-placed:
the scene sets time and weather, the journey only moves the camera; the rocks are what ArgoniaWorld.esm places).

    python3 -m tools.argonia_world.vegetation booth --out <shards> [--write]

Picks the six rock refs on the steepest ground, distinct forms first; the vantage stands VANTAGE_M downhill of each
rock (the side an open back or a lifted lip shows from) and EYE_M up, looking at it. Re-run after the ground lands.
"""
from __future__ import annotations

import math
from pathlib import Path

from tools.argonia_world import skyrim_units as su
from tools.argonia_world.vegetation import build

ROOT = Path(__file__).resolve().parents[3]
DIST, MIN_STAND_U, EYE_U = 4.0, 300.0, 120.0  # stand 4 x the rock's bound radius off (at least 300 units); eye 120 units up
WORLD = "ARG_Province"


def pick(out: Path, w) -> list[dict]:
    rock = {r["form_key"]: r["edid"] for r in w.query("SELECT form_key, edid FROM object_form WHERE role_id = 'rock'")}
    height = {r["form_key"]: float(r["bound_z1"] - r["bound_z0"]) for r in w.query(
        "SELECT form_key, bound_z0, bound_z1 FROM object_form WHERE role_id = 'rock'")}
    radius = {r["form_key"]: max(1.0, max(abs(r["bound_x0"]), abs(r["bound_x1"]), abs(r["bound_y0"]), abs(r["bound_y1"])))
              for r in w.query("SELECT form_key, bound_x0, bound_x1, bound_y0, bound_y1 FROM object_form WHERE role_id = 'rock'")}
    cand = []
    for c in build.read_cells(out):
        for r in c["refs"]:
            b = c["bases"][r[1]]
            if b in rock:
                tilt = math.hypot(r[5], r[6])
                cand.append({"form_key": b, "edid": rock[b], "fid": r[0], "cell": (c["x"], c["y"]), "x": r[2],
                             "y": r[3], "z": r[4], "radius": radius[b], "rx": r[5], "ry": r[6], "rz": r[7], "scale": r[8], "tilt": tilt})
                cand[-1]["radius"] *= r[8]
                cand[-1]["height"] = height[b] * r[8]
    cand.sort(key=lambda d: -d["tilt"])
    seen, out_ = set(), []
    for d in cand:  # distinct forms first, then the steepest of the rest
        if d["form_key"] not in seen:
            seen.add(d["form_key"])
            out_.append(d)
    out_ += [d for d in cand if d not in out_]
    return out_[:6]


def _ground_units(src, x: float, y: float) -> float:
    """The generated ground's height at a Skyrim-frame point, in units (bilinear on the province grid)."""
    import numpy as np
    from tools.argonia_world.terrain import grid
    sp = su.VERTEX_SPACING_UNITS
    c = x / sp - grid.CX0 * grid.Q
    r = src.n - (y / sp - grid.CY0 * grid.Q)
    r0, c0 = int(np.clip(math.floor(r), 0, src.n - 1)), int(np.clip(math.floor(c), 0, src.n - 1))
    fr, fc = min(max(r - r0, 0.0), 1.0), min(max(c - c0, 0.0), 1.0)
    g = src.ground
    h = (g[r0, c0] * (1 - fr) * (1 - fc) + g[r0, c0 + 1] * (1 - fr) * fc + g[r0 + 1, c0] * fr * (1 - fc)
         + g[r0 + 1, c0 + 1] * fr * fc)
    return su.metres_to_units(float(h))


def vantage(d: dict, src) -> tuple[float, float, float, float, float]:
    """(x, y, z units, heading deg, pitch deg down): on the ground DIST x the rock's bound radius downhill of it
    (the side an open back or a lifted lip shows from), eye EYE_U above that ground, aimed at the rock's base
    (its z plus half its height: the rock's middle, not the origin under the ground, which at 4 radii out put the rock
    out of frame in round 1). The downhill bearing is
    the ground's: step out along -grad at the rock, so the still looks up the slope at it."""
    # downhill from the ground itself (r6: the Euler lean's sign put five of six stands uphill of their rock, the
    # still looking down past it, round 2: 1 of 6 framed): the generated ground's fall over +-STEP_U at the rock
    e = 128.0
    hx = _ground_units(src, d["x"] - e, d["y"]) - _ground_units(src, d["x"] + e, d["y"])
    hy = _ground_units(src, d["x"], d["y"] - e) - _ground_units(src, d["x"], d["y"] + e)
    n = math.hypot(hx, hy)
    ux, uy = (hx / n, hy / n) if n > 1e-6 else (0.0, -1.0)  # flat ground (decision 0034): stand south
    k = stand(d)
    x, y = d["x"] + ux * k, d["y"] + uy * k
    heading = math.degrees(math.atan2(d["x"] - x, d["y"] - y)) % 360  # Skyrim: 0 = north, clockwise
    z = _ground_units(src, x, y) + EYE_U
    pitch = math.degrees(math.atan2(z - (d["z"] + d["height"] / 2), k))
    return x, y, z, heading, max(-60.0, min(pitch, 60.0))


def journey(rocks: list[dict], src, weather: dict[tuple[int, int], str]) -> str:
    lines = ["# Rock booth (1.15 §e.2), generated by `python3 -m tools.argonia_world.vegetation booth --write`: six of",
             "# our placed rocks (sunk by their OBND, conformed to the slope), a first-person still each, standing on",
             "# the ground 4 bound radii (300 units at least) downhill, eye 120 units up, aimed at the rock's middle, `camera: first`, noon in the region's",
             "# own clear weather (no fog over the base). Reader checklist per still: sunk (no open bottom), no gap",
             "# under the downhill lip, no hollow back, leans with the slope not against it. Never set what it tests.",
             "id: rock-booth", "runner: 1", "crash_risk: low", "scene: rock-booth", "camera: first", "steps:"]
    for n, d in enumerate(rocks, 1):
        x, y, z, h, pitch = vantage(d, src)
        cx, cy = d["cell"]
        lines += [f"- name: rock-{n}-{d['edid'].lower()}",
                  f"  # {d['form_key']} ref {d['fid']:06X} in cell ({cx},{cy}), tilt {math.degrees(d['tilt']):.1f} deg,"
                  f" scale {d['scale']:.2f}, bound radius {d['radius']:.0f} u, stand {k_of(d):.0f} u off",
                  f"  # subject: {d['x']:.0f} {d['y']:.0f} {d['z'] + d['height'] / 2:.0f}",
                  "  do:", "  - console:", f"      line: cow {WORLD} {cx} {cy}", "      settle: 60", "  - wait: 8",
                  "  - console:", "      line: set gamehour to 12",
                  "  - console:", f"      line: player.setpos x {x:.0f}", "  - console:",
                  f"      line: player.setpos y {y:.0f}", "  - console:", f"      line: player.setpos z {z:.0f}",
                  "  - console:", f"      line: player.setangle z {h:.0f}", "  - console:",
                  f"      line: player.setangle x {pitch:.0f}", "  - console:", "      line: player.setangle y 0", "  - wait: 6",
                  "  - console:", f"      line: fw {weather[d['cell']]}",   # AFTER the teleport and its settle (the new cell's region weather replaces an earlier force); look.booth_standard adds sw + settle
                  "  - console: " + f"prid ArgoniaWorld.esm|0x{d['fid']:06X}",  # the rock ref selected: getpos reads it
                  "  expect:", "  - console: getpos x", "    keep: rock_x", "  - console: getpos y", "    keep: rock_y",
                  "  - console: getpos z", "    keep: rock_z"]
    return "\n".join(lines) + "\n"


def stand(d: dict) -> float:
    return max(MIN_STAND_U, DIST * d["radius"])


def k_of(d: dict) -> float:
    return stand(d)


SCENE = """; Rock booth (1.15 §e.2): noon, so the stills read the rock's base and shadow line; the journey forces each
; rock's region clear weather (panel_weather); sets nothing it tests
set gamehour to 12
"""


def region_weather(w, cells) -> dict[tuple[int, int], str]:
    """Each cell's region noon weather (the panel's own table): its clear weather, so fog does not hide the base."""
    from tools.argonia_world.regions import panel_weather
    noon = {t["land_region"]: t["noon"]["edid"] for t in panel_weather.table(w)}
    reg = build.cell_regions(w)
    return {c: noon.get(reg.get(c), "SkyrimClear") for c in cells}


def write(out: Path, w) -> list[dict]:
    from tools.argonia_world.terrain.grid import Sources
    rocks = pick(out, w)
    src = Sources.load(apron=False)
    wx = region_weather(w, {d["cell"] for d in rocks})
    (ROOT / "tests" / "journeys" / "rock-booth.yaml").write_text(journey(rocks, src, wx))
    (ROOT / "tests" / "scenes" / "rock-booth.txt").write_text(SCENE)
    return rocks
