"""The core rules' tables as C++ (goal G11.2): no number of a skse/core rule is typed into C++.

Reads the sheet (attribute, skill, skill_bands, sheet_rules, class_rules and the core_* tables), progression and
condition tables (condition_term, condition_shape*) through db.py and writes data-only headers to
skse/core/generated/argonia/core/: tables_sheet.h, tables_progression.h, tables_conditions.h, tables_actions.h
and the topic store's fixture, fixture_topics.h (topic_tables.py).

    python3 -m tools.argonia_world.core_tables            # write the headers
    python3 -m tools.argonia_world.core_tables --check    # the gate: exit 1 and a diff when a header is stale
"""
from __future__ import annotations

import argparse
import difflib
import re
import sys
from pathlib import Path

from tools.argonia_world import db

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "skse" / "core" / "generated" / "argonia" / "core"
HEADERS = ("sheet", "progression", "conditions", "actions")

# C++ keywords and alternative tokens a world id could collide with (85's `not`).
_KEYWORDS = {"and", "or", "not", "xor", "bitand", "bitor", "compl", "default", "delete", "new", "class", "struct",
             "union", "enum", "int", "double", "bool", "char", "float", "long", "short", "signed", "unsigned",
             "void", "auto", "case", "switch", "if", "else", "for", "while", "do", "return", "break", "continue",
             "const", "static", "public", "private", "protected", "template", "typename", "this", "true", "false",
             "namespace", "using", "operator", "friend", "virtual", "inline", "register", "goto", "try", "catch",
             "throw", "export", "module", "import", "concept", "requires", "mutable", "explicit"}


def ident(s: str) -> str:
    """A world id as a C++ identifier: '-' and '.' become '_', a keyword gets a trailing '_'."""
    out = re.sub(r"[^0-9A-Za-z_]", "_", s)
    if out[0].isdigit():
        out = "_" + out
    return out + "_" if out in _KEYWORDS else out


def num(v: float | int | None) -> str:
    """A number as a C++ double literal that round-trips exactly."""
    r = repr(float(v))
    return r if ("e" in r or "." in r) else r + ".0"


def opt(v, render=num) -> str:
    return "std::nullopt" if v is None else render(v)


def sv(s: str | None) -> str:
    return '""' if not s else '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _enum(name: str, ids: list[str], underlying: str = "std::uint8_t") -> list[str]:
    return [f"enum class {name} : {underlying} {{ {', '.join(ident(i) for i in ids)} }};",
            f"inline constexpr std::size_t k{name}Count = {len(ids)};",
            f"inline constexpr std::array<std::string_view, {len(ids)}> k{name}Names{{"
            + ", ".join(sv(i) for i in ids) + "};"]


def _constants(w: db.World, header: str) -> list[str]:
    out = []
    for m in w.values("SELECT id FROM core_module WHERE header = ? ORDER BY id", header):
        rows = w.query("SELECT id, value, design_ref FROM core_constant WHERE module = ? ORDER BY id", m)
        if not rows:
            continue
        out.append(f"namespace {ident(m)} {{")
        out += [f"inline constexpr double {ident(r['id'])} = {num(r['value'])};  // {r['design_ref']}" for r in rows]
        out.append(f"}}  // namespace {ident(m)}")
    return out


def _wrap(header: str, includes: list[str], body: list[str]) -> str:
    lines = [f"// tables_{header}.h: GENERATED by tools/argonia_world/core_tables.py from the world database",
             "// (decision 0030; goal G11.2). Data only. Do not edit: change the rows through db.py and regenerate.",
             "#pragma once", *[f"#include <{i}>" for i in includes], "",
             "namespace argonia::core::gen {", "", *body, "", "}  // namespace argonia::core::gen", ""]
    return "\n".join(lines)


def sheet(w: db.World) -> str:
    attrs = w.values("SELECT id FROM attribute ORDER BY id")
    skills = w.values("SELECT id FROM skill ORDER BY id")
    specs = w.values("SELECT id FROM specialisation ORDER BY id")
    fams = w.values("SELECT id FROM skill_family ORDER BY id")
    bands = w.values("SELECT DISTINCT band FROM skill_bands ORDER BY band")
    fields = w.query("SELECT id, kind FROM core_stat_field ORDER BY id")
    tiers = w.query("SELECT * FROM core_burden_tier ORDER BY ord")
    a = lambda i: f"AttrId::{ident(i)}"  # noqa: E731
    b = []
    b += _enum("AttrId", attrs)
    b.append(f"inline constexpr std::array<double, {len(attrs)}> kAttributeReference{{"
             + ", ".join(num(v) for v in w.values("SELECT reference FROM attribute ORDER BY id")) + "};")
    b += ["", *_enum("Specialisation", specs), "", *_enum("SkillFamily", fams), "", *_enum("SkillId", skills), ""]
    b += ["struct SkillRow {", "  AttrId gov;                          // governing attribute: the trainer cap",
          "  std::optional<AttrId> score;         // the attribute its score uses; none: the score is the skill",
          "  std::optional<double> score_divisor; // replaces the curve's attribute divisor (Alchemy's Int/10)",
          "  Specialisation spec;", "  SkillFamily family;", "};",
          f"inline constexpr std::array<SkillRow, {len(skills)}> kSkills{{{{"]
    for r in w.query("SELECT * FROM skill ORDER BY id"):
        b.append(f"    {{{a(r['gov'])}, {opt(r['score'], a)}, {opt(r['score_divisor'])}, "
                 f"Specialisation::{ident(r['spec'])}, SkillFamily::{ident(r['family'])}}},  // {r['id']}")
    b += ["}};", "", *_enum("Band", bands), "",
          "struct BandRow { SkillId skill; Band band; double lo; double hi; };  // lo at score 0, hi at score 100"]
    rows = w.query("SELECT * FROM skill_bands ORDER BY skill_id, band")
    b.append(f"inline constexpr std::array<BandRow, {len(rows)}> kSkillBands{{{{")
    b += [f"    {{SkillId::{ident(r['skill_id'])}, Band::{ident(r['band'])}, {num(r['x'])}, {num(r['y'])}}},"
          for r in rows]
    b += ["}};", ""]
    for table in ("sheet_rules", "class_rules"):
        rows = w.query(f'SELECT * FROM "{table}" ORDER BY id')
        if len(rows) != 1:
            raise SystemExit(f"{table}: the generator expects exactly one row, found {len(rows)}")
        r = rows[0]
        b.append(f"namespace {table} {{")
        b += [f"inline constexpr double {ident(k)} = {num(r[k])};" for k in r.keys()
              if k not in ("id", "design_ref") and isinstance(r[k], (int, float))]
        b.append(f"}}  // namespace {table}")
    b += ["", *_enum("EffectOp", w.values("SELECT id FROM core_effect_op ORDER BY ord")), "",
          "enum class FieldKind : std::uint8_t { pool, resist, factor, per_int, flag };",
          *_enum("StatField", [f["id"] for f in fields]),
          f"inline constexpr std::array<FieldKind, {len(fields)}> kStatFieldKind{{"
          + ", ".join(f"FieldKind::{f['kind']}" for f in fields) + "};", ""]
    b += [*_enum("BurdenTier", [t["id"] for t in tiers]),
          "struct BurdenRow {", "  std::optional<double> below_ratio;      // the tier ends below this carried/capacity",
          "  double stamina_mult;", "  std::optional<double> climb_drain_mult; // none: cannot climb",
          "  std::optional<double> roll_distance;    // none: no roll", "  std::optional<double> roll_recovery;",
          "  std::optional<double> iframe_scale;", "  bool can_run;", "};",
          f"inline constexpr std::array<BurdenRow, {len(tiers)}> kBurdenTiers{{{{"]
    b += [f"    {{{opt(t['below_ratio'])}, {num(t['stamina_mult'])}, {opt(t['climb_drain_mult'])}, "
          f"{opt(t['roll_distance'])}, {opt(t['roll_recovery'])}, {opt(t['iframe_scale'])}, "
          f"{'true' if t['can_run'] else 'false'}}},  // {t['id']}" for t in tiers]
    arm = w.query("SELECT * FROM core_armour_skill ORDER BY skill")
    b += ["}};", "", "struct ArmourSkillRow { SkillId skill; std::optional<double> rating_mult; double win_weight; "
          "double hit_weight; };", f"inline constexpr std::array<ArmourSkillRow, {len(arm)}> kArmourSkills{{{{"]
    b += [f"    {{SkillId::{ident(r['skill'])}, {opt(r['rating_mult'])}, {num(r['win_weight'])}, "
          f"{num(r['hit_weight'])}}}," for r in arm]
    wear = w.query("SELECT * FROM core_wear_kind ORDER BY id")
    b += ["}};", "", *_enum("WearKind", [r["id"] for r in wear]),
          "enum class WearPer : std::uint8_t { damage, use, second };",
          f"inline constexpr std::array<WearPer, {len(wear)}> kWearPer{{"
          + ", ".join(f"WearPer::{r['per']}" for r in wear) + "};", "", *_constants(w, "sheet")]
    return _wrap("sheet", ["array", "cstddef", "cstdint", "optional", "string_view"], b)


def progression(w: db.World) -> str:
    classes = w.query("SELECT * FROM core_skill_class ORDER BY ord")
    uses = w.query("SELECT * FROM core_use ORDER BY id")
    beds = w.query("SELECT * FROM core_bed_tier ORDER BY ord")
    resp = w.query("SELECT * FROM core_respawn_class ORDER BY id")
    sp = w.query("SELECT * FROM core_use_skill_points ORDER BY use, skill")
    rpl = w.values("SELECT ranks FROM core_ranks_per_level ORDER BY level")
    levels = w.values("SELECT level FROM core_ranks_per_level ORDER BY level")
    if levels != list(range(1, len(levels) + 1)):
        raise SystemExit(f"core_ranks_per_level: levels must run 1..n without a gap, got {levels}")
    b = [*_enum("SkillClass", [c["id"] for c in classes]),
         "struct SkillClassRow { double xp_factor; int ranks_per_credit; };",
         f"inline constexpr std::array<SkillClassRow, {len(classes)}> kSkillClasses{{{{"]
    b += [f"    {{{num(c['xp_factor'])}, {c['ranks_per_credit']}}},  // {c['id']}" for c in classes]
    b += ["}};", "", *_enum("UseKind", [u["id"] for u in uses]),
          "enum class UseUnit : std::uint8_t { use, second, metre, percent };",
          "struct UseRow { double points; UseUnit unit; bool scaled; };",
          f"inline constexpr std::array<UseRow, {len(uses)}> kUses{{{{"]
    b += [f"    {{{num(u['points'])}, UseUnit::{u['unit']}, {'true' if u['scaled'] else 'false'}}},  // {u['id']}"
          for u in uses]
    b += ["}};", "struct UseSkillPointsRow { UseKind use; SkillId skill; double points; };",
          f"inline constexpr std::array<UseSkillPointsRow, {len(sp)}> kUseSkillPoints{{{{"]
    b += [f"    {{UseKind::{ident(r['use'])}, SkillId::{ident(r['skill'])}, {num(r['points'])}}}," for r in sp]
    b += ["}};", "", "// Entry n - 1 takes level n to n + 1; every level past the last asks the last.",
          f"inline constexpr std::array<int, {len(rpl)}> kRanksPerLevel{{{', '.join(str(r) for r in rpl)}}};", "",
          *_enum("BedTier", [r["id"] for r in beds]), "struct BedTierRow { double xp_mult; double hours; };",
          f"inline constexpr std::array<BedTierRow, {len(beds)}> kBedTiers{{{{"]
    b += [f"    {{{num(r['xp_mult'])}, {num(r['hours'])}}},  // {r['id']}" for r in beds]
    b += ["}};", "", *_enum("RespawnClass", [r["id"] for r in resp]),
          "struct RespawnRow { bool on_rest; bool until_cleared; };",
          f"inline constexpr std::array<RespawnRow, {len(resp)}> kRespawnClasses{{{{"]
    b += [f"    {{{'true' if r['on_rest'] else 'false'}, {'true' if r['until_cleared'] else 'false'}}},  // {r['id']}"
          for r in resp]
    b += ["}};", "", *_constants(w, "progression")]
    return _wrap("progression", ["array", "cstddef", "cstdint", "string_view", "argonia/core/tables_sheet.h"], b)


def conditions(w: db.World) -> str:
    terms = w.query("SELECT t.id, t.kind, s.shape, s.native FROM condition_term t JOIN condition_shape s "
                    "ON s.term = t.id WHERE t.kind != 'action' ORDER BY t.id")
    unshaped = w.values("SELECT id FROM condition_term WHERE kind != 'action' AND id NOT IN "
                        "(SELECT term FROM condition_shape)")
    if unshaped:
        raise SystemExit(f"condition_shape: no shape for {unshaped}")
    shapes = ["all", "any", "not", "truth", "flag", "at_least", "compare", "is", "rank_at_least", "after", "before",
              "calendar", "time_of_day"]
    ops = w.query("SELECT * FROM condition_op ORDER BY ord")
    bands = w.query("SELECT * FROM core_disposition_band ORDER BY ord")
    b = [*_enum("Term", [t["id"] for t in terms], "std::uint16_t"),
         f"enum class Shape : std::uint8_t {{ {', '.join(ident(s) for s in shapes)} }};",
         "enum class ArgKind : std::uint8_t { id, int_, op, enum_, bool_ };",
         "struct ArgSpec { ArgKind kind; bool optional; };",
         "struct TermRow {", "  Shape shape;", "  std::string_view native;  // the Skyrim condition function; empty: "
         "evaluated here and mirrored", "  std::size_t first_arg, arg_count;      // into kArgSpecs",
         "  std::size_t first_value, value_count;  // into kValues: the enum argument's closed set, in rank order",
         "};"]
    specs, values, rows = [], [], []
    kind = {"id": "id", "int": "int_", "op": "op", "enum": "enum_", "bool": "bool_"}
    for t in terms:
        a = w.query("SELECT kind, optional FROM condition_shape_arg WHERE term = ? ORDER BY ord", t["id"])
        v = w.values("SELECT value FROM condition_shape_value WHERE term = ? ORDER BY ord", t["id"]) + w.values(
            "SELECT season_id FROM condition_shape_season WHERE term = ? ORDER BY ord", t["id"])  # the season table
        rows.append(f"    {{Shape::{ident(t['shape'])}, {sv(t['native'])}, {len(specs)}, {len(a)}, {len(values)}, "
                    f"{len(v)}}},  // {t['id']}")
        specs += [f"ArgSpec{{ArgKind::{kind[r['kind']]}, {'true' if r['optional'] else 'false'}}}" for r in a]
        values += [sv(x) for x in v]
    b += [f"inline constexpr std::array<TermRow, {len(rows)}> kTerms{{{{", *rows, "}};",
          f"inline constexpr std::array<ArgSpec, {len(specs)}> kArgSpecs{{{{"]
    b += [f"    {s}," for s in specs]
    b += ["}};", f"inline constexpr std::array<std::string_view, {len(values)}> kValues{{"]
    b += [f"    {', '.join(values[i:i + 8])}," for i in range(0, len(values), 8)]
    b += ["};", "", f"enum class Op : std::uint8_t {{ {', '.join(o['name'] for o in ops)} }};",
          f"inline constexpr std::array<std::string_view, {len(ops)}> kOpSymbols{{"
          + ", ".join(sv(o["id"]) for o in ops) + "};", "",
          *_enum("DispositionBand", [r["id"] for r in bands]),
          f"inline constexpr std::array<double, {len(bands)}> kDispositionBandMin{{"
          + ", ".join(num(r["min"]) for r in bands) + "};", "", *_constants(w, "conditions")]
    return _wrap("conditions", ["array", "cstddef", "cstdint", "string_view"], b)


def actions(w: db.World) -> str:
    verbs = w.values("SELECT id FROM condition_term WHERE kind = 'action' ORDER BY id")
    unshaped = w.values("SELECT id FROM condition_term WHERE kind = 'action' AND id NOT IN "
                        "(SELECT term FROM action_shape_arg)")
    if unshaped:
        raise SystemExit(f"action_shape_arg: no arguments for {unshaped}")
    kind = {"id": "id", "int": "int_", "bool": "bool_"}
    b = [*_enum("Verb", verbs, "std::uint16_t"), "enum class ActionArgKind : std::uint8_t { id, int_, bool_ };",
         "struct ActionArgSpec { ActionArgKind kind; bool optional; };",
         "struct VerbRow { std::size_t first_arg, arg_count; };  // into kActionArgSpecs"]
    specs, rows = [], []
    for v in verbs:
        a = w.query("SELECT kind, optional FROM action_shape_arg WHERE term = ? ORDER BY ord", v)
        rows.append(f"    {{{len(specs)}, {len(a)}}},  // {v}")
        specs += [f"    ActionArgSpec{{ActionArgKind::{kind[r['kind']]}, {'true' if r['optional'] else 'false'}}},"
                  for r in a]
    b += [f"inline constexpr std::array<VerbRow, {len(rows)}> kVerbs{{{{", *rows, "}};",
          f"inline constexpr std::array<ActionArgSpec, {len(specs)}> kActionArgSpecs{{{{", *specs, "}};"]
    return _wrap("actions", ["array", "cstddef", "cstdint", "string_view"], b)


def fixture_topics(w: db.World) -> str:
    from tools.argonia_world import topic_tables
    text = _wrap("fixture_topics", ["array", "cstddef", "cstdint", "string_view"], topic_tables.render(w))
    return text.replace("// tables_fixture_topics.h: GENERATED by tools/argonia_world/core_tables.py",
                        "// fixture_topics.h: GENERATED by tools/argonia_world/topic_tables.py (via core_tables.py)")


def render(w: db.World) -> dict[str, str]:
    out = {f"tables_{h}.h": f(w) for h, f in (("sheet", sheet), ("progression", progression),
                                              ("conditions", conditions), ("actions", actions))}
    out["fixture_topics.h"] = fixture_topics(w)
    return out


def stale(rendered: dict[str, str], out: Path = OUT) -> list[str]:
    """A unified diff line list per header that differs from what is on disk (empty: current)."""
    diff = []
    for name, text in rendered.items():
        p = out / name
        old = p.read_text(encoding="utf-8") if p.exists() else ""
        if old != text:
            diff += list(difflib.unified_diff(old.splitlines(), text.splitlines(), f"committed/{name}",
                                              f"regenerated/{name}", lineterm="", n=1))
    return diff


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when a committed header differs from the tables")
    args = ap.parse_args(argv)
    rendered = render(db.open())
    if args.check:
        diff = stale(rendered)
        if diff:
            print("skse/core/generated is stale; run `python3 -m tools.argonia_world.core_tables`:", file=sys.stderr)
            print("\n".join(diff[:80]), file=sys.stderr)
            return 1
        print(f"core tables: {len(rendered)} headers current")
        return 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in rendered.items():
        (OUT / name).write_text(text, encoding="utf-8")
    print(f"core tables: wrote {', '.join(rendered)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
