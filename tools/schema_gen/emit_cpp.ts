// The C++ twin of the message schema: typed structs, enums, traits, and strict JSON encode/decode over
// argonia/core/json.h. Pure C++ (no Skyrim type), header-only, so skse/core's tests and ArgoniaCore include it.
import type { MessageDef, StructDef, Ty } from "../../ui/schema/types.ts";
import { cppEnumerator, cppMember, type Model } from "./model.ts";

const HEADER = (src: string) =>
  `// ${src}: GENERATED by tools/schema_gen from ui/schema/*.ts (1.1 §c). Do not edit: change the schema and run\n` +
  `// \`node --experimental-strip-types tools/schema_gen/gen.ts\`; the gate (skse/check.sh) refuses a stale twin.\n`;

const lit = (n: number): string => (Number.isInteger(n) ? `${n}.0` : String(n));
const cstr = (s: string): string => JSON.stringify(s);

function cppType(t: Ty): string {
  switch (t.kind) {
    case "str": return "std::string";
    case "int": return "std::int64_t";
    case "num": return "double";
    case "bool": return "bool";
    case "enum": return t.def.name;
    case "ref": return t.def.name;
    case "list": return `std::vector<${cppType(t.of)}>`;
    case "opt": return `std::optional<${cppType(t.of)}>`;
  }
}

const defaultInit = (t: Ty): string => (t.kind === "int" || t.kind === "num" ? " = 0" : t.kind === "bool" ? " = false" :
  t.kind === "enum" ? `{}` : "");

// An expression building the json::Value of `src`.
function enc(t: Ty, src: string, depth: number): string {
  switch (t.kind) {
    case "str": return `json::Value::string(${src})`;
    case "int": return `json::Value::number(double(${src}))`;
    case "num": return `json::Value::number(${src})`;
    case "bool": return `json::Value::boolean(${src})`;
    case "enum": case "ref": return `to_json(${src})`;
    case "list": {
      const e = `e${depth}`, a = `a${depth}`;
      return `[&] { json::Array ${a}; ${a}.reserve(${src}.size()); for (const auto& ${e} : ${src}) ${a}.push_back(${enc(t.of, e, depth + 1)}); return json::Value::array(std::move(${a})); }()`;
    }
    case "opt": throw new Error("opt is handled at the field");
  }
}

const bounds = (t: { min?: number; max?: number }, int: boolean) =>
  `${t.min === undefined ? (int ? "-json::kMaxSafeInt" : "-(std::numeric_limits<double>::max)()") : lit(t.min)}, ` +
  `${t.max === undefined ? (int ? "json::kMaxSafeInt" : "(std::numeric_limits<double>::max)()") : lit(t.max)}`;

// Statements decoding json::Value `src` into `dst`; `path` is a std::string expression.
function dec(t: Ty, src: string, dst: string, path: string, depth: number, pad: string): string {
  switch (t.kind) {
    case "str": case "bool": return `${pad}if (!json::read(${src}, ${dst}, ${path}, err)) return false;\n`;
    case "int": return `${pad}if (!json::read_int(${src}, ${dst}, ${bounds(t, true)}, ${path}, err)) return false;\n`;
    case "num": return `${pad}if (!json::read_num(${src}, ${dst}, ${bounds(t, false)}, ${path}, err)) return false;\n`;
    case "enum": case "ref": return `${pad}if (!from_json(${src}, ${dst}, ${path}, err)) return false;\n`;
    case "list": {
      const a = `a${depth}`, i = `i${depth}`;
      return `${pad}{\n` +
        `${pad}  const json::Array* ${a} = (${src}).as_array();\n` +
        `${pad}  if (!${a}) return json::fail(err, ${path}, "want a list");\n` +
        `${pad}  ${dst}.clear();\n${pad}  ${dst}.reserve(${a}->size());\n` +
        `${pad}  for (std::size_t ${i} = 0; ${i} < ${a}->size(); ++${i}) {\n` +
        `${pad}    ${dst}.emplace_back();\n` +
        dec(t.of, `(*${a})[${i}]`, `${dst}.back()`, `${path} + "[" + std::to_string(${i}) + "]"`, depth + 1, pad + "    ") +
        `${pad}  }\n${pad}}\n`;
    }
    case "opt": throw new Error("opt is handled at the field");
  }
}

function emitStruct(s: StructDef): string {
  const fields = Object.entries(s.fields);
  const members = fields.map(([k, t]) => `  ${cppType(t)} ${cppMember(k)}${defaultInit(t)};  // ${t.doc}\n`).join("");
  return `// ${s.doc}\nstruct ${s.name} {\n${members}  bool operator==(const ${s.name}&) const = default;\n};\n`;
}

// One name per field's JSON value: MSVC (C4456) reads consecutive if-init declarations of one name as shadowing.
const fx = (k: string) => `f_${cppMember(k)}`;

function emitCodec(s: StructDef): string {
  const fields = Object.entries(s.fields);
  let toj = `inline json::Value to_json(const ${s.name}& v) {\n  json::Object o;\n`;
  toj += fields.length ? `  o.reserve(${fields.length});\n` : `  (void)v;\n`;
  for (const [k, t] of fields) {
    const m = `v.${cppMember(k)}`;
    if (t.kind === "opt") toj += `  if (${m}) o.push_back({${cstr(k)}, ${enc(t.of, `*${m}`, 0)}});\n`;
    else toj += `  o.push_back({${cstr(k)}, ${enc(t, m, 0)}});\n`;
  }
  toj += `  return json::Value::object(std::move(o));\n}\n`;

  let fromj = `inline bool from_json(const json::Value& j, ${s.name}& out, const std::string& path, std::string& err) {\n` +
    `  json::Fields f(j, path, err);\n  if (!f.ok()) return false;\n` + (fields.length ? "" : `  (void)out;\n`);
  for (const [k, t] of fields) {
    const m = `out.${cppMember(k)}`;
    const p = `path + ${cstr("." + k)}`;
    if (t.kind === "opt") {
      fromj += `  if (const json::Value* ${fx(k)} = f.opt(${cstr(k)})) {\n    ${m}.emplace();\n` +
        dec(t.of, `*${fx(k)}`, `*${m}`, p, 0, "    ") + `  } else {\n    ${m}.reset();\n  }\n`;
    } else {
      fromj += `  if (const json::Value* ${fx(k)} = f.req(${cstr(k)})) {\n` + dec(t, `*${fx(k)}`, m, p, 0, "    ") +
        `  } else {\n    return false;\n  }\n`;
    }
  }
  fromj += `  return f.done();\n}\n`;
  return toj + fromj;
}

export function emitCpp(model: Model): string {
  const { messages, structs, enums } = model;
  const push = messages.filter((m) => m.dir === "push");
  const intents = messages.filter((m) => m.dir === "intent");
  const names = (ms: readonly MessageDef[]) => ms.map((m) => m.body.name).join(", ");
  let o = HEADER("messages.h");
  o += `#pragma once\n#include "argonia/core/json.h"\n\n`;
  for (const h of ["array", "cstddef", "cstdint", "expected", "limits", "optional", "string", "string_view", "type_traits",
    "utility", "variant", "vector"]) o += `#include <${h}>\n`;
  o += `\nnamespace argonia::core::msg {\n\n`;
  o += `// FNV-1a 64 of the schema's shape; the views' twin carries the same value (ui/schema/generated/messages.ts).\n`;
  o += `inline constexpr std::string_view kSchemaHash = ${cstr(model.hash)};\n\n`;
  o += `enum class Direction : std::uint8_t { push, intent };  // push: ArgoniaCore -> view; intent: view -> ArgoniaCore\n\n`;
  for (const e of enums) {
    o += `// ${e.doc}\nenum class ${e.name} : std::uint8_t { ${e.values.map(cppEnumerator).join(", ")} };\n`;
    o += `inline constexpr std::array<std::string_view, ${e.values.length}> k${e.name}Names{${e.values.map(cstr).join(", ")}};\n\n`;
  }
  for (const s of structs) o += emitStruct(s) + "\n";

  o += `// The wire identity of each message.\ntemplate <class T>\nstruct Traits;\n`;
  for (const m of messages) {
    o += `template <>\nstruct Traits<${m.body.name}> {\n  static constexpr std::string_view type = ${cstr(m.type)};\n` +
      `  static constexpr std::uint32_t version = ${m.version};\n  static constexpr Direction dir = Direction::${m.dir};\n};\n`;
  }
  o += `\nusing Push = std::variant<${names(push)}>;\nusing Intent = std::variant<${names(intents)}>;\n` +
    `using Message = std::variant<${names(messages)}>;\n\n`;
  o += `struct MessageInfo { std::string_view type; std::uint32_t version; Direction dir; };\n`;
  o += `inline constexpr std::array<MessageInfo, ${messages.length}> kMessages{{\n` +
    messages.map((m) => `    {${cstr(m.type)}, ${m.version}, Direction::${m.dir}},\n`).join("") + `}};\n\n`;

  o += `namespace detail {\n\n`;
  for (const e of enums) {
    const list = e.values.join(", ");
    o += `inline json::Value to_json(${e.name} v) { return json::Value::string(std::string(k${e.name}Names[std::size_t(v)])); }\n`;
    o += `inline bool from_json(const json::Value& j, ${e.name}& out, const std::string& path, std::string& err) {\n` +
      `  const std::string* s = j.as_string();\n  if (!s) return json::fail(err, path, ${cstr(`want one of ${list}`)});\n` +
      `  for (std::size_t i = 0; i < k${e.name}Names.size(); ++i)\n` +
      `    if (*s == k${e.name}Names[i]) { out = ${e.name}(i); return true; }\n` +
      `  return json::fail(err, path, "'" + *s + ${cstr(`' is not one of ${list}`)});\n}\n`;
  }
  o += `\n`;
  for (const s of structs) o += emitCodec(s) + "\n";

  o += `template <class V>\nstd::expected<V, std::string> decode_as(std::string_view text, std::string_view refuse) {\n` +
    `  auto j = json::parse(text);\n  if (!j) return std::unexpected("message: " + j.error());\n` +
    `  std::string err;\n  json::Fields f(*j, "message", err);\n  if (!f.ok()) return std::unexpected(err);\n` +
    `  std::string type;\n  std::int64_t v = 0;\n  const json::Value* t = f.req("type");\n` +
    `  if (!t || !json::read(*t, type, "message.type", err)) return std::unexpected(err);\n` +
    `  const json::Value* vv = f.req("v");\n` +
    `  if (!vv || !json::read_int(*vv, v, 1, json::kMaxSafeInt, "message.v", err)) return std::unexpected(err);\n` +
    `  const json::Value* body = f.req("body");\n  if (!body || !f.done()) return std::unexpected(err);\n`;
  for (const m of messages) {
    const n = m.body.name;
    o += `  if (type == ${cstr(m.type)}) {\n    if constexpr (std::is_constructible_v<V, ${n}>) {\n` +
      `      if (v != ${m.version})\n        return std::unexpected(${cstr(`${m.type} version `)} + std::to_string(v) + ` +
      `${cstr(`: this build speaks version ${m.version}`)});\n` +
      `      ${n} m;\n      if (!from_json(*body, m, ${cstr(`${m.type} body`)}, err)) return std::unexpected(err);\n` +
      `      return V{std::in_place_type<${n}>, std::move(m)};\n    } else {\n` +
      `      return std::unexpected(${cstr(`${m.type}: `)} + std::string(refuse));\n    }\n  }\n`;
  }
  o += `  return std::unexpected("message type '" + type + "' is not in the schema");\n}\n\n}  // namespace detail\n\n`;

  o += `// Encoding checks the value against the schema (ranges, finite numbers) and refuses what the other end would.\n`;
  for (const m of messages) {
    const n = m.body.name;
    o += `inline std::expected<std::string, std::string> encode(const ${n}& m) {\n` +
      `  json::Value body = detail::to_json(m);\n  ${n} check;\n  std::string err;\n` +
      `  if (!detail::from_json(body, check, ${cstr(`${m.type} body`)}, err)) return std::unexpected(err);\n` +
      `  return json::envelope(${cstr(m.type)}, ${m.version}, std::move(body));\n}\n`;
  }
  o += `\n// Any message in the schema.\ninline std::expected<Message, std::string> decode(std::string_view text) {\n` +
    `  return detail::decode_as<Message>(text, "");\n}\n`;
  o += `// What ArgoniaCore accepts from a view: intents only.\n` +
    `inline std::expected<Intent, std::string> decode_intent(std::string_view text) {\n` +
    `  return detail::decode_as<Intent>(text, "a view never sends state; ArgoniaCore accepts intents only");\n}\n`;
  o += `// What a view accepts (mirrored by the TS twin's decodePush).\n` +
    `inline std::expected<Push, std::string> decode_push(std::string_view text) {\n` +
    `  return detail::decode_as<Push>(text, "an intent is never pushed to a view");\n}\n\n`;
  o += `}  // namespace argonia::core::msg\n`;
  return o;
}
