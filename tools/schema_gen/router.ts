// data/router/surfaces.json -> generated/argonia/core/router_table.h: the menu router's registry (1.1 §d) as
// constexpr rows. Checked here: unique camelCase ids, kinds and replacements from the closed sets, every hook
// referenced exists and is used, menu names unique, a view replacement names its view, and the
// dialogue surface carries 1.3 §b's intercept.
import { SchemaError } from "./model.ts";

interface Raw { [k: string]: unknown }
const fail = (why: string): never => { throw new SchemaError(`surfaces.json: ${why}`); };
const q = (s: unknown): string => JSON.stringify(String(s ?? ""));
const ID = /^[a-z][A-Za-z0-9]*$/;

export function emitRouter(text: string): string {
  let doc: Raw;
  try { doc = JSON.parse(text) as Raw; } catch (e) { return fail(`not JSON: ${(e as Error).message}`); }
  const kinds = doc.kinds as string[], reps = doc.replacements as string[];
  const hooks = doc.hooks as Raw[], surfaces = doc.surfaces as Raw[];
  if (![kinds, reps, hooks, surfaces].every(Array.isArray)) fail("kinds, replacements, hooks and surfaces are lists");
  const hookIds = hooks.map((h) => String(h.id));
  const seen = new Set<string>();
  for (const h of hooks) {
    if (!ID.test(String(h.id)) || seen.has(String(h.id))) fail(`hook id ${q(h.id)} is not a unique camelCase id`);
    seen.add(String(h.id));
    if (!h.mechanism || !h.chunk) fail(`hook ${h.id}: mechanism and chunk are required`);
  }
  const used = new Set<string>(), menus = new Set<string>();
  for (const s of surfaces) {
    const id = String(s.id);
    if (!ID.test(id) || seen.has(id)) fail(`surface id ${q(s.id)} is not a unique camelCase id`);
    seen.add(id);
    for (const k of Object.keys(s))
      if (!["id", "kind", "menu", "inventory", "replacement", "by", "hook", "chunk", "note"].includes(k)) fail(`${id}: unknown key '${k}'`);
    if (!kinds.includes(String(s.kind))) fail(`${id}: kind ${q(s.kind)} is not one of ${kinds.join(", ")}`);
    if (!reps.includes(String(s.replacement))) fail(`${id}: replacement ${q(s.replacement)} is not one of ${reps.join(", ")}`);
    if (!hookIds.includes(String(s.hook))) fail(`${id}: hook ${q(s.hook)} is not in hooks`);
    used.add(String(s.hook));
    if (!s.chunk) fail(`${id}: chunk is required`);
    if (s.replacement === "view" && !s.by) fail(`${id}: a view replacement names its view in 'by'`);
    if (s.menu) {
      if (menus.has(String(s.menu))) fail(`${id}: menu ${q(s.menu)} has two rows`);
      menus.add(String(s.menu));
    }
  }
  for (const h of hookIds) if (!used.has(h)) fail(`hook ${h} carries no surface`);
  const dialogue = surfaces.find((s) => s.kind === "dialogue");
  if (!dialogue || dialogue.hook !== "dialogueIntercept") fail("the dialogue surface must carry the dialogueIntercept hook (1.3 §b)");

  const n = surfaces.length, h = hooks.length;
  let o = `// router_table.h: GENERATED by tools/schema_gen from data/router/surfaces.json (1.1 §d). Do not edit: change\n` +
    `// the JSON and run \`node --experimental-strip-types tools/schema_gen/gen.ts\`; the gate refuses a stale file.\n` +
    `#pragma once\n#include <array>\n#include <cstddef>\n#include <cstdint>\n#include <string_view>\n\n` +
    `namespace argonia::core::gen {\n\n`;
  const en = (name: string, type: string, vals: string[]) =>
    `enum class ${name} : ${type} { ${vals.join(", ")} };\ninline constexpr std::size_t k${name}Count = ${vals.length};\n` +
    `inline constexpr std::array<std::string_view, ${vals.length}> k${name}Names{${vals.map(q).join(", ")}};\n\n`;
  o += en("SurfaceKind", "std::uint8_t", kinds) + en("Replacement", "std::uint8_t", reps);
  o += en("HookId", "std::uint8_t", hookIds) + en("SurfaceId", "std::uint16_t", surfaces.map((s) => String(s.id)));
  o += `struct HookRow { std::string_view mechanism, chunk; };\n` +
    `inline constexpr std::array<HookRow, ${h}> kHooks{{\n` +
    hooks.map((x) => `    {${q(x.mechanism)}, ${q(x.chunk)}},  // ${x.id}\n`).join("") + `}};\n\n`;
  o += `struct SurfaceRow {\n  SurfaceKind kind;\n  std::string_view menu;       // the engine's menu name; empty for a non-menu surface\n` +
    `  std::string_view inventory;  // the immersion inventory row\n  Replacement replacement;\n` +
    `  std::string_view by;         // the view or flow that replaces it\n  HookId hook;\n  std::string_view chunk;\n};\n` +
    `inline constexpr std::array<SurfaceRow, ${n}> kSurfaces{{\n` +
    surfaces.map((s) => `    {SurfaceKind::${s.kind}, ${q(s.menu)}, ${q(s.inventory)}, Replacement::${s.replacement}, ${q(s.by)}, ` +
      `HookId::${s.hook}, ${q(s.chunk)}},  // ${s.id}\n`).join("") + `}};\n\n}  // namespace argonia::core::gen\n`;
  return o;
}
