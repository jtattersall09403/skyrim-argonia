// The views' twin of the message schema: TS types plus a strict validator whose refusals read like the C++ twin's.
// Erasable syntax only (no enum, no namespace), so Node runs it with --experimental-strip-types and any bundler
// takes it as is.
import type { MessageDef, StructDef, Ty } from "../../ui/schema/types.ts";
import type { Model } from "./model.ts";

const q = (s: string): string => JSON.stringify(s);

function tsType(t: Ty): string {
  switch (t.kind) {
    case "str": return "string";
    case "int": case "num": return "number";
    case "bool": return "boolean";
    case "enum": case "ref": return t.def.name;
    case "list": return `${tsType(t.of)}[]`;
    case "opt": return tsType(t.of);
  }
}

// An expression: null when `x` fits `t`, else the refusal.
function chk(t: Ty, x: string, p: string, depth: number): string {
  switch (t.kind) {
    case "str": return `(typeof ${x} === "string" ? null : bad(${p}, "want a string"))`;
    case "bool": return `(typeof ${x} === "boolean" ? null : bad(${p}, "want true or false"))`;
    case "int": return `whole(${x}, ${t.min ?? "-MAX_SAFE"}, ${t.max ?? "MAX_SAFE"}, ${p})`;
    case "num": return `real(${x}, ${t.min ?? "-Number.MAX_VALUE"}, ${t.max ?? "Number.MAX_VALUE"}, ${p})`;
    case "enum": case "ref": return `check${t.def.name}(${x}, ${p})`;
    case "list": {
      const e = `e${depth}`, i = `i${depth}`;
      return `each(${x}, ${p}, (${e}: unknown, ${i}: string) => ${chk(t.of, e, i, depth + 1)})`;
    }
    case "opt": throw new Error("opt is handled at the field");
  }
}

function emitChecker(s: StructDef): string {
  const fields = Object.entries(s.fields);
  let o = `function check${s.name}(x: unknown, p: string): string | null {\n` +
    `  const o = members(x, p, ${JSON.stringify(fields.map(([k]) => k))});\n  if (typeof o === "string") return o;\n` +
    `  let e: string | null;\n`;
  for (const [k, t] of fields) {
    const v = `o[${q(k)}]`, path = `p + ${q("." + k)}`;
    if (t.kind === "opt") o += `  if (${v} !== undefined && (e = ${chk(t.of, v, path, 0)}) !== null) return e;\n`;
    else o += `  if (${v} === undefined) return bad(${path}, "missing");\n  if ((e = ${chk(t, v, path, 0)}) !== null) return e;\n`;
  }
  return o + `  return null;\n}\n`;
}

export function emitTs(model: Model): string {
  const { messages, structs, enums } = model;
  const env = (m: MessageDef) => `{ type: ${q(m.type)}; v: ${m.version}; body: ${m.body.name} }`;
  const union = (ms: readonly MessageDef[]) => ms.map((m) => `\n  | ${env(m)}`).join("") || " never";
  let o = `// messages.ts: GENERATED by tools/schema_gen from ui/schema/*.ts (1.1 §c). Do not edit: change the schema and\n` +
    `// run \`node --experimental-strip-types tools/schema_gen/gen.ts\`; the gate refuses a stale twin. The C++ twin is\n` +
    `// skse/core/generated/argonia/core/messages.h. Views never hold game state: they render pushes and send intents.\n\n`;
  o += `export const schemaHash = ${q(model.hash)};\n\n`;
  for (const e of enums) o += `/** ${e.doc} */\nexport type ${e.name} = ${e.values.map(q).join(" | ")};\n`;
  o += `\n`;
  for (const s of structs) {
    o += `/** ${s.doc} */\nexport interface ${s.name} {\n`;
    for (const [k, t] of Object.entries(s.fields)) o += `  /** ${t.doc} */\n  ${k}${t.kind === "opt" ? "?" : ""}: ${tsType(t)};\n`;
    o += `}\n`;
  }
  const push = messages.filter((m) => m.dir === "push"), intents = messages.filter((m) => m.dir === "intent");
  o += `\nexport type PushMessage =${union(push)};\nexport type IntentMessage =${union(intents)};\n` +
    `export type Message = PushMessage | IntentMessage;\nexport type Direction = "push" | "intent";\n` +
    `export type Result<T> = { ok: true; value: T } | { ok: false; error: string };\n\n`;
  o += `export const messageTable: readonly { type: string; version: number; dir: Direction }[] = [\n` +
    messages.map((m) => `  { type: ${q(m.type)}, version: ${m.version}, dir: ${q(m.dir)} },\n`).join("") + `];\n\n`;

  o += `const MAX_SAFE = Number.MAX_SAFE_INTEGER;\n` +
    `const bad = (p: string, why: string): string => \`\${p}: \${why}\`;\n` +
    `const isObject = (x: unknown): x is Record<string, unknown> =>\n  typeof x === "object" && x !== null && !Array.isArray(x);\n` +
    `function members(x: unknown, p: string, known: readonly string[]): Record<string, unknown> | string {\n` +
    `  if (!isObject(x)) return bad(p, "want an object");\n` +
    `  for (const k of Object.keys(x)) if (!known.includes(k) && x[k] !== undefined) return bad(\`\${p}.\${k}\`, "not in the schema");\n` +
    `  return x;\n}\n` +
    `function whole(x: unknown, lo: number, hi: number, p: string): string | null {\n` +
    `  if (typeof x !== "number" || !Number.isSafeInteger(x)) return bad(p, "want a whole number");\n` +
    `  return x < lo || x > hi ? bad(p, \`\${x} is outside \${lo}..\${hi}\`) : null;\n}\n` +
    `function real(x: unknown, lo: number, hi: number, p: string): string | null {\n` +
    `  if (typeof x !== "number" || !Number.isFinite(x)) return bad(p, "want a number");\n` +
    `  return x < lo || x > hi ? bad(p, \`\${x} is outside \${lo}..\${hi}\`) : null;\n}\n` +
    `function each(x: unknown, p: string, f: (e: unknown, p: string) => string | null): string | null {\n` +
    `  if (!Array.isArray(x)) return bad(p, "want a list");\n` +
    `  for (let i = 0; i < x.length; ++i) { const e = f(x[i], \`\${p}[\${i}]\`); if (e !== null) return e; }\n  return null;\n}\n\n`;
  for (const e of enums) {
    o += `const ${e.name}Values: readonly string[] = [${e.values.map(q).join(", ")}];\n` +
      `function check${e.name}(x: unknown, p: string): string | null {\n` +
      `  if (typeof x !== "string") return bad(p, ${q(`want one of ${e.values.join(", ")}`)});\n` +
      `  return ${e.name}Values.includes(x) ? null : bad(p, \`'\${x}' is not one of ${e.values.join(", ")}\`);\n}\n`;
  }
  for (const s of structs) o += emitChecker(s);
  o += `\nconst bodies: Record<string, (x: unknown, p: string) => string | null> = {\n` +
    messages.map((m) => `  ${q(m.type)}: check${m.body.name},\n`).join("") + `};\n\n`;

  o += `const REFUSE: Record<Direction, string> = {\n` +
    `  push: "a view never sends state; ArgoniaCore accepts intents only",\n` +
    `  intent: "an intent is never pushed to a view",\n};\n\n`;
  o += `// Checks one decoded message against the schema; \`accept\` limits the direction.\n` +
    `export function validate(x: unknown, accept?: Direction): Result<Message> {\n` +
    `  const o = members(x, "message", ["type", "v", "body"]);\n  if (typeof o === "string") return { ok: false, error: o };\n` +
    `  if (o.type === undefined) return { ok: false, error: "message.type: missing" };\n` +
    `  if (typeof o.type !== "string") return { ok: false, error: "message.type: want a string" };\n` +
    `  if (o.v === undefined) return { ok: false, error: "message.v: missing" };\n` +
    `  const ve = whole(o.v, 1, MAX_SAFE, "message.v");\n  if (ve !== null) return { ok: false, error: ve };\n` +
    `  if (o.body === undefined) return { ok: false, error: "message.body: missing" };\n` +
    `  const info = messageTable.find((m) => m.type === o.type);\n` +
    `  if (!info) return { ok: false, error: \`message type '\${o.type}' is not in the schema\` };\n` +
    `  if (accept !== undefined && info.dir !== accept) return { ok: false, error: \`\${info.type}: \${REFUSE[info.dir]}\` };\n` +
    `  if (o.v !== info.version) return { ok: false, error: \`\${info.type} version \${o.v}: this build speaks version \${info.version}\` };\n` +
    `  const be = bodies[info.type](o.body, \`\${info.type} body\`);\n` +
    `  return be === null ? { ok: true, value: o as unknown as Message } : { ok: false, error: be };\n}\n\n`;
  o += `function parse(text: string): Result<unknown> {\n` +
    `  try { return { ok: true, value: JSON.parse(text) as unknown }; }\n` +
    `  catch (e) { return { ok: false, error: \`message: JSON error: \${(e as Error).message}\` }; }\n}\n\n`;
  o += `// What a view accepts from ArgoniaCore: state pushes only.\n` +
    `export function decodePush(text: string): Result<PushMessage> {\n  const j = parse(text);\n` +
    `  return (j.ok ? validate(j.value, "push") : j) as Result<PushMessage>;\n}\n` +
    `// What ArgoniaCore accepts (the C++ twin's decode_intent); for the L3 harness and tests.\n` +
    `export function decodeIntent(text: string): Result<IntentMessage> {\n  const j = parse(text);\n` +
    `  return (j.ok ? validate(j.value, "intent") : j) as Result<IntentMessage>;\n}\n` +
    `// A view sends only what the schema holds: the intent is checked before it leaves.\n` +
    `export function encodeIntent(m: IntentMessage): Result<string> {\n  const r = validate(m, "intent");\n` +
    `  return r.ok ? { ok: true, value: JSON.stringify(m) } : r;\n}\n` +
    `// For mocks and the L3 harness, which stand in for ArgoniaCore.\n` +
    `export function encodePush(m: PushMessage): Result<string> {\n  const r = validate(m, "push");\n` +
    `  return r.ok ? { ok: true, value: JSON.stringify(m) } : r;\n}\n`;
  return o;
}
