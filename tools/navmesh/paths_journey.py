"""tests/journeys/navmesh-paths.yaml from the DB: 200 bridge `nav` path requests between planned stands, then the
frame time in the densest vegetation cell (checks.md 1.15 row 146).

The stands are the world's own: 20 positioned places and 20 land spawn points (creatures/build), spread over the
province by farthest-point picking; each anchor is paired with its 5 nearest dry spawn points 600-7500 units off (the
bridge's `nav` searches the loaded cells only, so both ends sit inside the 5x5 grid a teleport to the anchor loads).
The bar: at least 99 % of the 200 nav steps green (at most 2 red); the planner reads it from report.json.

    python -m tools.navmesh.paths_journey [--out tests/journeys/navmesh-paths.yaml]
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from tools.argonia_world import skyrim_units as su

ROOT = Path(__file__).resolve().parents[2]
ANCHORS, PER = 40, 5
NEAR_U, FAR_U = 600.0, 7500.0  # under 2 cells (8192 u): the grid a teleport loads
STEEP_DEG = 30.0


def spread(pts: list[tuple], n: int) -> list[tuple]:
    """Farthest-point picking, deterministic (first point is the most south-westerly)."""
    if not pts:
        return []
    pick = [min(pts, key=lambda p: (p[0] + p[1], p[0]))]
    d = [math.hypot(p[0] - pick[0][0], p[1] - pick[0][1]) for p in pts]
    while len(pick) < min(n, len(pts)):
        i = max(range(len(pts)), key=d.__getitem__)
        pick.append(pts[i])
        d = [min(d[j], math.hypot(p[0] - pts[i][0], p[1] - pts[i][1])) for j, p in enumerate(pts)]
    return pick


def pairs(anchors: list[tuple], spawns: list[tuple], per: int = PER) -> list[tuple[tuple, list[tuple]]]:
    out = []
    for a in anchors:
        near = sorted((s for s in spawns if NEAR_U <= math.hypot(s[0] - a[0], s[1] - a[1]) <= FAR_U),
                      key=lambda s: math.hypot(s[0] - a[0], s[1] - a[1]))
        if len(near) >= per:
            out.append((a, near[:per]))
    return out


ARRIVE_U = su.metres_to_units(3)  # arrival tolerance: 3 m in Skyrim units


def _f(v: float) -> str:
    return f"{v:.0f}"


def render(groups, dense_cell, bar=(16.67, 22.22)) -> str:
    n = sum(len(p) for _, p in groups)
    lines = [
        "# GENERATED by `python -m tools.navmesh.paths_journey` (lane 1.15-r6-navmesh-lodkey): edit the tool, not this.",
        f"# 1.15 row 146: {n} bridge `nav` path requests between planned stands (places and land spawn points from the DB),",
        "# grouped per anchor (a teleport loads the 5x5 grid, both ends inside it), then the frame time in the densest",
        f"# vegetation cell. Bar: >= 99 % of the {n} nav steps green (at most {n - math.ceil(0.99 * n)} red), and",
        f"# frametime p50 <= {bar[0]} ms, p99 <= {bar[1]} ms. Steps are independent: a red nav step is counted, not fatal.",
        "id: navmesh-paths",
        "reach: [esm, tools/navmesh]   # the pass ledger's inputs",
        "runner: 1",
        "crash_risk: low",
        "scene: creature-spots",  # god mode only: a creature at a stand does not end the visit
        "independent_steps: true",
        "steps:",
    ]
    for gi, (a, ps) in enumerate(groups):
        lines += [f"  - name: a{gi:02d}-arrive",
                  f"    why: '{a[3]}'",
                  f"    do: [{{teleport: \"pos {_f(a[0])} {_f(a[1])} {_f(a[2] + 20)}\"}}, {{settle: {{cap: 30, min: 3}}}}]",
                  # teleport, then the settle (Loading Menu closed, position still; the runner caps a settle at 30 s), then
                  # arrival read from the bridge's player state as the other journeys do (the console's GetInWorldspace with
                  # an editor-id argument prints 0 whatever the worldspace): worldspace, and x/y within 3 m of the target
                  "    expect:",
                  "      - {read: [player], path: worldspace.editor_id, eq: ARG_Province, within: 30}"]
        for axis, v in (("x", a[0]), ("y", a[1])):
            lines += [f"      - {{read: [player], path: pos.{axis}, ge: {_f(v - ARRIVE_U)}, le: {_f(v + ARRIVE_U)}, within: 30}}"]
        for k, p in enumerate(ps):
            lines += [f"  - name: a{gi:02d}-nav-{k}",
                      f"    expect: [{{read: [nav, {_f(a[0])}, {_f(a[1])}, {_f(a[2])}, {_f(p[0])}, {_f(p[1])}, {_f(p[2])}],"
                      " path: length, gt: 0}]"]
    cx, cy = dense_cell
    lines += ["  - name: dense-frametime",
              f"    why: 'the densest vegetation cell ({cx}, {cy}), out/terrain/vegetation/summary.json densest[0]'",
              f"    do: [{{console: \"cow ARG_Province {cx} {cy}\"}}, {{wait: 15}}]",
              "    expect:",
              f"      - {{read: [frametime, 600], path: p50_ms, le: {bar[0]}, within: 120}}",
              f"      - {{read: [frametime, 600], path: p99_ms, le: {bar[1]}, within: 120}}"]
    return "\n".join(lines) + "\n"


def build() -> str:
    from tools.argonia_world import db
    from tools.argonia_world.creatures import build as cb
    from tools.journeys import Build, ground_slope_deg
    w, b = db.open(), Build()
    ok = lambda x, y: not b.wet(x, y) and ground_slope_deg(b, x, y) < STEEP_DEG  # noqa: E731
    run = _run(w, cb)  # the cached run the creature journeys read (tools/journeys/gen.py _kinds_spawns)
    spawns = [(r["x"], r["y"], b.ground_u(r["x"], r["y"]), "spawn " + r["class"]) for r in run["refs"]
              if r["kind"] == "spawn" and r["medium"] in ("land", "shore") and ok(r["x"], r["y"])]
    places = [(p[0], p[1], b.ground_u(p[0], p[1]), "place " + p[3]) for p in cb.places(w) if ok(p[0], p[1])]
    anchors = spread(places, ANCHORS) + spread(spawns, 2 * ANCHORS)  # places first; spares where one has too few partners
    groups, seen = [], set()
    for a, ps in pairs(anchors, spawns):
        if (round(a[0]), round(a[1])) in seen:
            continue
        seen.add((round(a[0]), round(a[1])))
        groups.append((a, ps))
        if len(groups) == ANCHORS:
            break
    dense = json.loads((ROOT / "out" / "terrain" / "vegetation" / "summary.json").read_text())["densest"][0][:2]
    return render(groups, tuple(dense))


def _run(w, cb):
    from tools.argonia_world.terrain.grid import Sources
    from tools.argonia_world.water import solve
    ground = sorted((ROOT / "out" / "terrain" / "build").glob("*/ground-f32.npy"), key=lambda p: p.stat().st_mtime)[-1]
    x0, y0 = su.PROVINCE_CELL_SW
    cells = [(x, y) for y in range(y0, y0 + su.PROVINCE_CELLS) for x in range(x0, x0 + su.PROVINCE_CELLS)]
    return cb.run(w, Sources.load(ground=ground), solve.load(w), cells, None, log=lambda s: None,
                  veg=ROOT / "out" / "terrain" / "vegetation", cache=ROOT / "out" / "terrain" / "creatures")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="paths_journey")
    ap.add_argument("--out", type=Path, default=ROOT / "tests" / "journeys" / "navmesh-paths.yaml")
    a = ap.parse_args(argv)
    text = build()
    a.out.write_text(text)
    print(f"{a.out}: {text.count('-nav-')} nav steps")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
