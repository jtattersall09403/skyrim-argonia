"""Flora sets per region (nw-02 step 6): the plant, tree and rock bases each region grows, by habitat.

Two steps:
  pull   out/newworld/research/flora_catalogue.json (the flora study's catalogue) -> newworld/sources/flora/bases.json:
         every catalogue row of BM&V, KoTM, Tropical Skyrim and Depths of Skyrim matched to a family
         (families.json), Nordic rows and props dropped, one base per mesh, seating from the measured refs.
  build  newworld/sources/flora/*.json -> the flora tables (schema.sql "Flora"); called by build_db.build() and
         runnable alone (`python -m tools.newworld.flora build`) to refresh only the flora tables.

A region's set: for each of its habitats (regions.json, citing the region research), each family the habitat
grows (habitats.json) times the region's boost, spread over a region-seeded subset of the family's bases, so two
regions that share a family still show different meshes.
"""
from __future__ import annotations

import hashlib
import json
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

from tools.argonia_world import db

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "newworld" / "sources" / "flora"
CATALOGUE = ROOT / "out" / "newworld" / "research" / "flora_catalogue.json"
MODS = ("BM&V", "KoTM", "TS", "Depths")      # the brief's priority: BM&V and KoTM first, TS and Depths second
MOD_RANK = {m: i for i, m in enumerate(MODS)}
TABLES = ("flora_class", "flora_family", "flora_base", "habitat", "habitat_family", "flora_guild",
          "flora_guild_member", "region_habitat", "region_family", "region_flora")
PICK_SHARE = 0.45      # of a family's bases a region grows (at least 2, at most PICK_MAX)
PICK_MAX = 8


def load(name: str) -> dict:
    return json.loads((SRC / name).read_text())


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def size_of(h: float) -> str:
    return "small" if h < 1 else "medium" if h < 5 else "large" if h < 20 else "huge"


def pull(catalogue: Path = CATALOGUE) -> list[dict]:
    fam = load("families.json")
    excl = re.compile(fam["exclude"])
    fams = [(f, re.compile(f["match"])) for f in fam["families"]]
    classes = fam["classes"]
    rows = [e for v in json.loads(catalogue.read_text())["catalogue"].values() for e in v if e["mod"] in MODS]
    rows.sort(key=lambda e: (MOD_RANK[e["mod"]], -sum(e["refs"].values()), e["form"]))
    out, seen_model, ids = [], set(), set()
    for e in rows:
        text = f"{e['edid']} {e['modl']} {e['visual']}".lower()
        h = float(e["dims_m"][2])
        if excl.search(text) or h < 0.05:
            continue
        override = next((why for k, why in fam["nordic_overrides"].items() if k in text), None)
        if e["nordic_flag"] and not override:
            continue
        name = f"{e['edid']} {e['modl']}".lower()
        f = next((f for f, rx in fams if rx.search(name)), None) or next((f for f, rx in fams if rx.search(text)), None)
        model = e["modl"].lower().replace("/", "\\")
        if f is None or (model, f["id"]) in seen_model:
            continue
        seen_model.add((model, f["id"]))
        cls = classes[f["class"]]
        seat = max(e.get("seating", {}).items(), key=lambda kv: kv[1]["n"], default=None)
        if seat and seat[1]["n"] >= 5:
            lo, med, hi = seat[1]["sink_m_p25_med_p75"]
            sink, world, scale = med, seat[0], seat[1]["scale_p5_med_p95"][1]
        else:
            lo = hi = world = scale = None
            sink = cls["sink_ratio"] * h if "sink_ratio" in cls else cls["sink_m"]
        bid = base = slug(f"{e['mod']}-{e['edid']}")
        n = 2
        while bid in ids:
            bid, n = f"{base}-{n}", n + 1
        ids.add(bid)
        out.append({"id": bid, "form_key": e["form"], "plugin": e["plugin"], "mod": e["mod"], "edid": e["edid"],
                    "model": e["modl"], "flora_family_id": f["id"], "size": size_of(h), "height_m": round(h, 2),
                    "sink_m": round(sink, 2), "sink_lo_m": lo, "sink_hi_m": hi, "sink_measured_in": world,
                    "scale_med": scale, "placed_refs": sum(e["refs"].values()),
                    "nordic_override": override if e["nordic_flag"] else None})
    out.sort(key=lambda r: r["id"])
    (SRC / "bases.json").write_text(json.dumps({"about": "Generated by `python -m tools.newworld.flora pull` from the "
                                                "flora study's catalogue; edit families.json, not this file.",
                                                "bases": out}, indent=1) + "\n")
    return out


def rank(region: str, base_id: str, mod: str) -> float:
    """A region-seeded order inside a family: a stable hash, nudged toward the brief's first-choice mods."""
    hv = int(hashlib.sha1(f"{region}/{base_id}".encode()).hexdigest()[:8], 16) / 0xFFFFFFFF
    return hv * (1.0 if MOD_RANK[mod] < 2 else 0.6)


def region_sets() -> tuple[dict, dict, dict, list[dict]]:
    """The authored sources resolved into rows: families, habitats, bases and the region_flora rows."""
    fam = load("families.json")
    families = {f["id"]: f for f in fam["families"]}
    habitats = {h["id"]: h for h in load("habitats.json")["habitats"]}
    bases = load("bases.json")["bases"]
    by_family = defaultdict(list)
    for b in bases:
        by_family[b["flora_family_id"]].append(b)
    rows = []
    for rid, r in sorted(load("regions.json")["regions"].items()):
        boost = {k: v[0] for k, v in r.get("boost", {}).items()}
        picks: dict[str, list[dict]] = {}
        acc: dict[tuple, dict] = {}
        for hid, (hshare, aspect, hwhy) in r["habitats"].items():
            h = habitats[hid]
            eff = {f: s * boost.get(f, 1.0) for f, s in h["families"].items()}
            eff = {f: s for f, s in eff.items() if s > 0 and by_family[f]
                   and not (families[f].get("water_only") and h["water"] == "dry")}
            tot = sum(eff.values())
            for f, s in eff.items():
                if f not in picks:
                    cand = sorted(by_family[f], key=lambda b: -rank(rid, b["id"], b["mod"]))
                    k = min(len(cand), max(2, min(PICK_MAX, math.ceil(len(cand) * PICK_SHARE))))
                    picks[f] = cand[:k]
                fd = families[f]
                water = None
                if h["water"] == "standing" and fd.get("standing_water_max_m") is not None:
                    water = min(h["depth_max_m"], fd["standing_water_max_m"])
                for b in picks[f]:
                    acc[(hid, b["id"])] = {"region_id": rid, "habitat_id": hid, "flora_base_id": b["id"],
                                           "weight": hshare * s / tot / len(picks[f]),
                                           "density_per_ha": round(h["density_per_ha"] * s / tot / len(picks[f]), 3),
                                           "water_max_m": water}
        wsum = sum(v["weight"] for v in acc.values())
        for v in acc.values():
            v["weight"] = round(v["weight"] / wsum, 5)
        rows += sorted(acc.values(), key=lambda v: (v["habitat_id"], v["flora_base_id"]))
    return families, habitats, {b["id"]: b for b in bases}, rows


def jaccard(rows: list[dict]) -> dict[tuple[str, str], float]:
    """Weighted Jaccard (sum of minima over sum of maxima) of every pair of regions' base weights."""
    w = defaultdict(lambda: defaultdict(float))
    for r in rows:
        w[r["region_id"]][r["flora_base_id"]] += r["weight"]
    regs = sorted(w)
    out = {}
    for i, a in enumerate(regs):
        for b in regs[i + 1:]:
            keys = set(w[a]) | set(w[b])
            out[(a, b)] = sum(min(w[a][k], w[b][k]) for k in keys) / sum(max(w[a][k], w[b][k]) for k in keys)
    return out


def build(w: db.World) -> None:
    fam = load("families.json")
    for cid, c in sorted(fam["classes"].items()):
        w.insert("flora_class", id=cid, tilt_factor=c["tilt_factor"], tilt_max_deg=c["tilt_max_deg"],
                 sink_m=c.get("sink_m"), sink_ratio=c.get("sink_ratio"), about=c["about"])
    families, habitats, bases, rows = region_sets()
    for f in families.values():
        sb = f.get("seabed") or [None, None]
        w.insert("flora_family", id=f["id"], flora_class_id=f["class"], standing_water_max_m=f.get("standing_water_max_m"),
                 water_only=int(bool(f.get("water_only"))), seabed_min_m=sb[0], seabed_max_m=sb[1],
                 cluster_size=f["cluster"], about=f["about"])
    w.insert_many("flora_base", bases.values())
    for h in habitats.values():
        w.insert("habitat", id=h["id"], name=h["name"], water=h["water"], depth_min_m=h.get("depth_min_m"),
                 depth_max_m=h.get("depth_max_m"), density_per_ha=h["density_per_ha"], about=h["about"])
        for f, s in h["families"].items():
            w.insert("habitat_family", habitat_id=h["id"], flora_family_id=f, share=s)
    for g in load("guilds.json")["guilds"]:
        w.insert("flora_guild", id=g["id"], lift=g["lift"], evidence=g["evidence"])
        for f, role in g["members"].items():
            w.insert("flora_guild_member", flora_guild_id=g["id"], flora_family_id=f, role=role)
    aspects = {a.id for a in w.rows("note_aspect")}
    for rid, r in load("regions.json")["regions"].items():
        for hid, (share, aspect, why) in r["habitats"].items():
            w.insert("region_habitat", region_id=rid, habitat_id=hid, share=share,
                     note_aspect_id=aspect if aspect in aspects else None, why=why)
        for f, (boost, aspect, why) in r.get("boost", {}).items():
            w.insert("region_family", region_id=rid, flora_family_id=f, boost=boost,
                     note_aspect_id=aspect if aspect in aspects else None, why=why)
    w.insert_many("region_flora", rows)


REPORT = ROOT / "docs" / "phases" / "new-worldspace-plan" / "research" / "nw-02-region-flora.md"


def report(w: db.World) -> str:
    """The per-region summary: counts, habitats, top bases, standing water, and the similarity numbers."""
    base = {b.id: b for b in w.rows("flora_base")}
    kind = {r.id: r.kind for r in w.rows("region")}
    rows = [dict(r._asdict()) if hasattr(r, "_asdict") else vars(r) for r in w.rows("region_flora")]
    j = jaccard(rows)
    land = [v for (a, b), v in j.items() if kind[a] == kind[b] == "land"]
    sea = [v for (a, b), v in j.items() if "sea" in (kind[a], kind[b])]
    top = sorted(j.items(), key=lambda kv: -kv[1])[:5]
    mods = defaultdict(int)
    for b in base.values():
        mods[b.mod] += 1
    out = ["# nw-02 region flora: the plant, tree and rock set of each region", "",
           "Built by `tools/newworld/flora.py` (`pull` from the flora study's catalogue, `build` into the db, `report` "
           "writes this file) from `newworld/sources/flora/` (families, habitats, guilds, regions). Tables: "
           "flora_class, flora_family, flora_base, habitat, habitat_family, flora_guild(_member), region_habitat, "
           "region_family, region_flora (schema.sql, Flora). Rules and evidence: "
           "[nw-02-flora-rules](nw-02-flora-rules.md).", "",
           f"Bases: {len(base)} ({', '.join(f'{m} {n}' for m, n in sorted(mods.items()))}), in "
           f"{len(w.rows('flora_family'))} families, {len(w.rows('habitat'))} habitats, "
           f"{len(w.rows('flora_guild'))} companion guilds; {len(rows)} region_flora rows.", "",
           "Nordic: catalogue rows with nordic_flag are dropped, plus Valenwood temperate trees (redwood, birch, "
           "maple, cedar) and props (wrecks, book towers, bones, coast-wave FX). One exception, kept with its reason "
           "in flora_base.nordic_override: the gkb mangrove meshes, flagged only for 'reachtree' in their file name.",
           "",
           "## Similarity (weighted Jaccard of the regions' base weights, sum of minima over sum of maxima)", "",
           f"- Land pairs: max {max(land):.3f}, mean {sum(land) / len(land):.3f} (test threshold 0.35).",
           f"- Pairs with a sea region: max {max(sea):.3f}, mean {sum(sea) / len(sea):.3f} (threshold 0.5: Depths "
           "ships only 3 corals, 3 seaweeds, 3 kelps and 3 clams, so the seabeds must share most of them).",
           "- Most alike: " + "; ".join(f"{a} / {b} {v:.3f}" for (a, b), v in top) + ".", "",
           "Within a region, a family's bases are a region-seeded subset (45 %, 2 to 8 bases), so regions sharing a "
           "family still show different meshes.", "",
           "## Standing water", "",
           "Bases stand in water only in a region's standing-water habitats (mangrove fringe, cypress swamp, drowned "
           "forest, reed marsh, open still water), to the lesser of the habitat's and the family's depth (mangrove, "
           "cypress, dead swamp trees 3.0 m; drowned forest cap 3.5 m; knees, reeds, logs 1.5 m; lilies 2.0 m; dry "
           "trees and palms 0.5 m). No habitat is flowing water; rivers carry riverine forest on their banks only.", "",
           "## Regions", ""]
    by = defaultdict(list)
    for r in rows:
        by[r["region_id"]].append(r)
    hab = {h.id: h for h in w.rows("habitat")}
    for reg in w.rows("region", order="id"):
        rs = by[reg.id]
        tot = defaultdict(float)
        for r in rs:
            tot[r["flora_base_id"]] += r["weight"]
        fams = defaultdict(float)
        for b, v in tot.items():
            fams[base[b].flora_family_id] += v
        wet = sorted({r["flora_base_id"] for r in rs if r["water_max_m"] is not None})
        rh = sorted(w.rows("region_habitat", region_id=reg.id), key=lambda h: -h.share)
        out += [f"### {reg.name} ({reg.kind}; {reg.biome})", "",
                f"- {len(tot)} bases in {len(fams)} families; {len(wet)} may stand in still water.",
                "- Habitats: " + ", ".join(f"{hab[h.habitat_id].name.lower()} {h.share:.0%}" for h in rh) + ".",
                "- Families: " + ", ".join(f"{f} {v:.0%}" for f, v in sorted(fams.items(), key=lambda kv: -kv[1])[:8])
                + ".",
                "- Top bases: " + ", ".join(f"{base[b].edid} ({base[b].mod}) {v:.1%}"
                                            for b, v in sorted(tot.items(), key=lambda kv: -kv[1])[:6]) + ".", ""]
    REPORT.write_text("\n".join(out))
    return str(REPORT)


def main(argv: list[str]) -> None:
    cmd = argv[1] if len(argv) > 1 else "build"
    if cmd == "pull":
        print(len(pull()), "bases")
        return
    if cmd == "report":
        print(report(db.open(ROOT / "newworld", cache=False)))
        return
    w = db.open(ROOT / "newworld", cache=False)
    for t in reversed(TABLES):      # children first
        w.con.execute(f'DELETE FROM "{t}"')
    build(w)
    w.save(TABLES)
    j = jaccard(region_sets()[3])
    (a, b), m = max(j.items(), key=lambda kv: kv[1])
    print({t: len(w.rows(t)) for t in TABLES}, f"max weighted Jaccard {m:.3f} ({a} / {b})")


if __name__ == "__main__":
    main(sys.argv)
