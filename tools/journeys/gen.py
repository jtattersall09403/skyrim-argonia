def panel_clear(b: Build, vid: str, x: float, y: float, yaw: float, log: list, w=None,
                region: str | None = None) -> tuple[float, float, float]:
    """A PANEL_CLEAR vantage moved to the nearest stand (PANEL_STEP_M grid within PANEL_CLEAR_M; per stand the yaw nearest
    the authored one, PANEL_TURN_DEG steps) on dry footing, standable, whose eye reads 0/0 (clearance) and whose near field
    holds at least the authored stand's water share (40% at most asked); every vantage's clearance is printed.
    Unchanged when it already reads 0/0 or none is found (warned). Returns (x, y, yaw)."""
    from tools.journeys import stand_bad, water_share
    cl = clearance(b, eye_of(b, x, y), yaw)
    if vid in PANEL_CLEAR and cl != (0, 0):
        need = min(water_share(b, x, y, yaw), 0.4)
        n = int(PANEL_CLEAR_M / PANEL_STEP_M)
        turns = sorted(range(0, 360, PANEL_TURN_DEG), key=lambda t: min(t, 360 - t))
        found, best = None, None
        for i, j in sorted(((i, j) for i in range(-n, n + 1) for j in range(-n, n + 1) if math.hypot(i, j) <= n),
                           key=lambda c: c[0] ** 2 + c[1] ** 2):
            px, py = x + i * PANEL_STEP_M * U, y + j * PANEL_STEP_M * U
            if b.soaked(px, py) or b.wet(px, py) or (region and _region_at(w, px, py) != region):
                continue   # dry, and in the vantage's own land region (the panel is per region class)
            ex, ey, ez = eye_of(b, px, py)
            dm = math.hypot(i, j) * PANEL_STEP_M
            for t in turns:
                h = (yaw + t) % 360
                c_ = clearance(b, (ex, ey, ez), h)
                if c_ != (0, 0) and (dm > FIT_REACH_M or best and (c_[1], sum(c_)) >= best[0]):
                    continue
                if water_share(b, px, py, h) < need:
                    continue
                a = math.radians(h)
                if stand_bad(b, px, py, (ex + math.sin(a) * 15 * U, ey + math.cos(a) * 15 * U, ez)):
                    continue
                if c_ != (0, 0):   # the fallback: within FIT_REACH_M, least canopy then fewest plants, nearest
                    best = ((c_[1], sum(c_)), px, py, h, dm, c_)
                    continue
                found = (px, py, h, math.hypot(i, j) * PANEL_STEP_M)
                break
            if found:
                break
        if not found and best and (best[0][0], best[0][1]) < (cl[1], sum(cl)):
            print(f"world-panel: WARNING {vid}: no stand within {PANEL_CLEAR_M:.0f} m reads 0/0; the least-hit one within "
                  f"{FIT_REACH_M:.0f} m is used ({best[5][0]}/{best[5][1]})")
            log.append({"journey": "world-panel", "step": vid, "moved_m": round(best[4], 1),
                        "why": f"clearance {cl[0]}/{cl[1]} -> {best[5][0]}/{best[5][1]}, yaw {yaw:.0f} -> {best[3]:.0f}",
                        "clear": True})
            x, y, yaw, cl = best[1], best[2], best[3], best[5]
        elif found:
            log.append({"journey": "world-panel", "step": vid, "moved_m": round(found[3], 1),
                        "why": f"clearance {cl[0]}/{cl[1]} -> 0/0, yaw {yaw:.0f} -> {found[2]:.0f}", "clear": True})
            x, y, yaw, cl = found[0], found[1], found[2], (0, 0)
        else:
            print(f"world-panel: WARNING {vid}: no stand within {PANEL_CLEAR_M:.0f} m reads 0/0")
    print(f"world-panel: {vid}: clearance {cl[0]}/{cl[1]} (plants on the eye line to 60 m / canopy over the eye within "
          f"10 m) at {x:.0f} {y:.0f} yaw {yaw:.0f}")
    return x, y, yaw


# -- sky-ab: the world panel's two sky vantages, bounds from the markers --------------------------------------------------
SKY_HEAD = """# The sky A/B (lane 1.15-r5-sky; owner #37, 2026-11-03): one coastal shore and one highland vantage of the world
# panel, each at noon and dawn 06:30, clear-dry forced by its runtime form id (sw + fw Argonia.esm|0x000E9B),
# first person, HUD off, the camera pitched 12 degrees up so the zenith is in frame. The planner runs it twice on
# one deploy: under the Community Shaders launch and the shaders-off launch. A reader answers per still: is the
# sky visible (blue zenith, sparse clouds), is there a flat grey veil or ceiling over it, is there a yellow or olive
# cast; then compares the two launches. Each step checks only that the teleport landed and the weather took.
# Generated by `python3 -m tools.journeys refresh --only sky-ab` (tools/journeys/gen.py): the landing bounds are the
# panel markers' current positions +-300 units; never hand-edit.
"""
SKY_STOPS = (("coastal-lagoon-shore", "ARG_Ref_PanelCoastalLagoonShore", 94),
             ("western-frontier-high", "ARG_Ref_PanelWesternFrontierHigh", 180))
SKY_WEATHER, SKY_TOL_U = "Argonia.esm|0x000E9B", 300


def sky_ab(b: Build, reach=None) -> tuple[str, list]:
    """(the journey's text, the markers' positions): the stops' landing bounds from the markers' positions in the build."""
    steps = [{"name": "first-person-no-hud", "do": [{"wait": 10}, {"hud": "off"}], "expect": []}]
    pos = []
    for key, edid, yaw in SKY_STOPS:
        r = b.ref(edid)
        if not r or "x" not in r:
            raise SystemExit(f"sky-ab: {edid} is no placed exterior marker of the build")
        x, y = round(r["x"]), round(r["y"])
        pos.append((edid, x, y))
        for when, hour in (("noon", 12), ("dawn", 6.5)):
            steps.append({
                "name": f"{key}-{when}",
                "do": [{"console": {"line": f"player.moveto {edid}", "settle": 60}},
                       {"console": f"player.setangle z {yaw}"}, {"console": "player.setangle x -12"},
                       {"console": f"set gamehour to {hour}"}, {"console": f"sw {SKY_WEATHER}"},
                       {"console": f"fw {SKY_WEATHER}"}, {"settle": {"cap": 14, "min": 3}}],
                "expect": [{"console": "player.GetInWorldspace ARG_Province", "contains": ">> 1"},
                           *[{"read": ["player"], "path": f"pos.{a}", op: v}
                             for a, c in (("x", x), ("y", y))
                             for op, v in (("gt", c - SKY_TOL_U), ("lt", c + SKY_TOL_U))],
                           {"read": ["weather"], "path": "current.editor_id", "eq": "ARG_Weather_clear_dry", "within": 20}]})
    j = {"id": "sky-ab", "reach": reach or ["esm", "tests/scenes/world-panel.txt", "data/dependencies.json"],
         "independent_steps": True, "runner": 1, "crash_risk": "medium", "scene": "world-panel", "camera": "first",
         "steps": steps}
    return SKY_HEAD + json.dumps(j, indent=1) + "\n", pos


def sky_ab_stale(b: Build) -> list[str]:
    """Why tests/journeys/sky-ab.yaml no longer matches the markers (empty when it does)."""
    import yaml
    p = JOURNEYS / "sky-ab.yaml"
    if not p.is_file():
        return []
    cur = yaml.safe_load(p.read_text())
    want = yaml.safe_load(sky_ab(b, cur.get("reach"))[0])
    out = []
    for a, w in zip(cur["steps"], want["steps"]):
        if a != w:
            out.append(f"{a['name']}: the landing bounds are not the marker's position +-{SKY_TOL_U} units "
                       f"(run `python3 -m tools.journeys refresh --only sky-ab`)")
    return out or ([] if cur == want else ["sky-ab differs from its generator (refresh --only sky-ab)"])
