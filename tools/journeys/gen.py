def junction_arc(w) -> dict:
    """The re-routed tracks' shared arc round the site (from the route rows): the line's points at the least distance
    from the site's centre (within JUNCTION_TOL_M) are the arc; its middle point by order, and the radius."""
    cx, cy = (w.query("SELECT position_m_x x, position_m_y y FROM place WHERE id = ?", JUNCTION_PLACE)[0][k] for k in ("x", "y"))
    mids = []
    for rid in JUNCTION_ROUTES:
        pts = [(q["x_m"], q["y_m"]) for q in w.query("SELECT x_m, y_m FROM road_point WHERE route_id = ? ORDER BY ord", rid)]
        d = [math.hypot(x - cx, y - cy) for x, y in pts]
        R = min(d)
        run = [p for p, k in zip(pts, d) if k - R <= JUNCTION_TOL_M]
        mids.append((run[len(run) // 2], R, len(run)))
    (x, y), R, n = mids[0]
    return {"x_m": x, "y_m": y, "r_m": R, "points": n, "centre_m": (cx, cy), "spread_m": max(math.hypot(m[0][0] - x, m[0][1] - y) for m in mids)}


