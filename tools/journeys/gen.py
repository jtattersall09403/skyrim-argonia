ROAD = "route.road.gideon-blackwood-road"
ROAD_AT = (("blackwood-20", 0.20), ("blackwood-flat-46", 0.46), ("blackwood-slope-57", 0.57))
ROAD_AHEAD_M = 25.0


def _along(pts: list[tuple[float, float]], f: float) -> tuple[float, float, int]:
    seg = [math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(pts, pts[1:])]
    want, acc = f * sum(seg), 0.0
    for i, s in enumerate(seg):
        if acc + s >= want:
            t = (want - acc) / s if s else 0.0
            return pts[i][0] + t * (pts[i + 1][0] - pts[i][0]), pts[i][1] + t * (pts[i + 1][1] - pts[i][1]), i
        acc += s
    return pts[-1][0], pts[-1][1], len(pts) - 2


def road_look(b: Build, w, log: list) -> str:
    path = JOURNEYS / "road-look.yaml"
    head = [ln for ln in path.read_text().splitlines() if ln.startswith("#")]
    pts = [su.province_to_skyrim(r["x_m"], r["y_m"]) for r in w.query(
        "SELECT x_m, y_m FROM road_point WHERE route_id = ? ORDER BY ord", ROAD)]
    total = sum(math.hypot(q[0] - p[0], q[1] - p[1]) for p, q in zip(pts, pts[1:]))
    lines = head + ["id: road-look", "look: world", "runner: 1", "independent_steps: true", "crash_risk: low",
                    "scene: claywater", "camera: first", "steps:",
                    "  - name: road-in", "    do: [{hud: \"off\"}]",
                    "    expect: [{console: \"player.GetInWorldspace ARG_Province\", contains: \">> 1\"}]"]
    for k, (name, f) in enumerate(ROAD_AT):
        ahead = ROAD_AHEAD_M * U / total
        sx, sy, _ = _along(pts, min(f + ahead, 1.0))
        subj = (sx, sy, b.ground_u(sx, sy) + 0.5 * U)  # the road's surface 25 m on, looking along it
        px, py, _ = _along(pts, f)  # down the road first; off it to either side when that line is wet or leafy
        f0 = place(b, subj, ROAD_AHEAD_M * U, around(math.degrees(math.atan2(px - sx, py - sy)) % 360))
        x, y = f0["x"], f0["y"]
        h, p = aim(eye_of(b, x, y), subj)
        log.append({"journey": "road-look", "step": name, "moved_m": f0["moved_m"], "why": f0["why"], "clear": f0["clear"]})
        lines += [f"  - name: {name}", f"    # subject: {subj[0]:.0f} {subj[1]:.0f} {subj[2]:.0f}",
                  f"    do: [{{hud: \"off\"}}, {{console: \"sw {CLEAR_DRY}\"}}, {{console: \"fw {CLEAR_DRY}\"}}, "
                  "{settle: {cap: 14, min: 3}},",
                  f"         {{console: \"player.setpos x {x:.0f}\"}}, {{console: \"player.setpos y {y:.0f}\"}}, "
                  f"{{console: \"player.setpos z {b.ground_u(x, y) + SEAT_U:.0f}\"}},",
                  f"         {{console: \"player.setangle z {h:.0f}\"}}, {{console: \"player.setangle x {p:.0f}\"}}, {{wait: 4}}]"]
        lines += ["    expect: [{read: [weather], path: current.editor_id, eq: ARG_Weather_clear_dry, within: 20}]",
                  "    reader: [the road the low line of a shallow worn trough along the middle of the frame, its dirt "
                  "blending into the land over ~4 m each side, no spike, wall or step along it, no Nordic piece]"]
    return "\n".join(lines) + "\n"


# -- the Claywater vantages ----------------------------------------------------------------------------------------------
CLAY_STAND_M = {"person": 3.5, "thing": 8.0}
MOVE = re.compile(r'\{console: "player\.moveto (ARG_Ref_\w+)(?: -?\d+){3}"\}, \{console: "player\.setangle z -?\d+"\}'
                  r'|\{console: "player\.moveto (ARG_Ref_\w+)"\}')


def claywater(b: Build, name: str, log: list) -> str:
    """Each moveto onto a ground-placed ref becomes a moveto beside it (dx dy dz off the ref) on dry ground with a
    clear eye line, facing it; refs with their own z (doors on porches) and hand offsets stay."""
    path = JOURNEYS / f"{name}.yaml"
    lines = path.read_text().splitlines()
    for i, ln in enumerate(lines):
        def sub(m):
            edid = m.group(1) or m.group(2)
            r = b.ref(edid)
            if r is None or r.get("interior") or r["own_z"]:
                return m.group(0)
            person = "Livia" in edid or "Signs" in edid or "Gaius" in edid or "Takes" in edid
            rz = b.water_u(r["x"], r["y"]) if b.wet(r["x"], r["y"]) else b.ground_u(r["x"], r["y"])
            subj = (r["x"], r["y"], rz + (1.0 if person else 0.5) * U)
            f = place(b, subj, CLAY_STAND_M["person" if person else "thing"] * U, around(180.0))
            x, y = f["x"], f["y"]
            h, _ = aim(eye_of(b, x, y), subj)
            log.append({"journey": name, "step": edid, "moved_m": f["moved_m"], "why": f["why"], "clear": f["clear"]})
            dz = b.ground_u(x, y) + SEAT_U - rz
            return (f'{{console: "player.moveto {edid} {x - r["x"]:.0f} {y - r["y"]:.0f} {dz:.0f}"}}, '
                    f'{{console: "player.setangle z {h:.0f}"}}')
        if "player.moveto" in ln:
            lines[i] = MOVE.sub(sub, ln)
    return "\n".join(lines) + "\n"


