def _shore(b: Build, x: float, y: float, ux: float, uy: float, limit_m: float = 400.0):
    """From a wet point, walk (ux, uy) to the first dry sample: the shore, or None."""
    for k in range(int(limit_m / SAMPLE_M)):
        px, py = x + ux * k * SAMPLE_M * U, y + uy * k * SAMPLE_M * U
        if not b.wet(px, py):
            return px, py
    return None


def _water_stop(b: Build, name: str, subj: tuple, ux: float, uy: float, log: list):
    """The stand SHORE_BACK_M past the shore met walking from the subject along (ux, uy), cleared of foliage."""
    sh = _shore(b, subj[0], subj[1], ux, uy)
    if sh is None:
        return None
    d = math.hypot(sh[0] - subj[0], sh[1] - subj[1]) + SHORE_BACK_M * U
    f = place(b, subj, d, around(math.degrees(math.atan2(ux, uy)) % 360))
    if not f["dry"]:
        return None
    return f   # the fit (_fit) logs the stand it settles on


