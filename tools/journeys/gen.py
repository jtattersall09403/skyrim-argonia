RIVER_HEAD = """# River steps (lane 1.15-r4-water, owner play test 3 findings 19 and 20): the three steepest kept steps of the water
# solve (water_step), three reaches turned to dry gullies, two still bodies; teleport, settle, one still each at the
# play camera. Generated by `python3 -m tools.journeys refresh` (tools/journeys/gen.py) from the build: never hand-edit.
# Reader checklist: at a step, the rapids line sits on the upper water at the edge and flows down; the skirt and
# ring sit on the lower water at the foot; no piece in the air or facing uphill; no water sheet edge hanging over
# ground. At a gully: no water surface, a dry bed. At a still body: the surface does not flow (no drift).
# Every stop (lane 1.15-r4-water-look): near and far water read as water, no marbled or blocky white-and-dark tiles.
id: river-steps
runner: 1
crash_risk: medium
scene: creature-spots
camera: third
steps:
"""
# The dry gullies and still bodies the water lane chose (lane-1.15-r4-water.md): their cells; the positions are the build's.
GULLIES = (("gully-1", "reach.1375-169", (-19, 58)), ("gully-2", "reach.97-2505", (-60, -15)),
           ("gully-3", "reach.70-1177", (-60, 26)))
STILLS = (("still-1", (-36, -8)), ("still-2", (-62, 24)))
STEP_STAND_M, BED_STAND_M = 18.0, 15.0


def _edge_mid(cx: int, cy: int, edge: str, lo: int, hi: int) -> tuple[float, float, float]:
    """The step's crossing midpoint on the cell edge (units) and the bearing from it into the lower cell."""
    ox, oy = su.cell_origin(cx, cy)
    m = (lo + hi) / 2 * su.VERTEX_SPACING_UNITS
    return {"n": (ox + m, oy + su.CELL_UNITS, 0.0), "s": (ox + m, oy, 180.0), "e": (ox + su.CELL_UNITS, oy + m, 90.0),
            "w": (ox, oy + m, 270.0)}[edge]


def _cell_low(b: Build, cx: int, cy: int, wet: bool | None = None) -> tuple[float, float, float]:
    """The cell's lowest LAND vertex (the bed) or, with `wet`, its wet vertex nearest the centre."""
    ox, oy = su.cell_origin(cx, cy)
    best = None
    for i in range(1, 32):
        for j in range(1, 32):
            x, y = ox + i * su.VERTEX_SPACING_UNITS, oy + j * su.VERTEX_SPACING_UNITS
            g = b.ground_u(x, y)
            if wet:
                if b.wet(x, y):
                    k = math.hypot(i - 16, j - 16)
                    if best is None or k < best[0]:
                        best = (k, x, y, b.water_u(x, y))
            elif best is None or g < best[0]:
                best = (g, x, y, g)
    if best is None:
        x, y = ox + su.CELL_UNITS / 2, oy + su.CELL_UNITS / 2
        return x, y, b.ground_u(x, y)
    return best[1], best[2], best[3]


def _cow_step(name: str, note: str, x: float, y: float, z: float, h: float, p: float, subj, first: bool) -> str:
    cx, cy = su.cell_of(x, y)
    return "\n".join([
        f"- name: {name}", f"  # {note}", f"  # subject: {subj[0]:.0f} {subj[1]:.0f} {subj[2]:.0f}", "  do:",
        *(["  - hud: off", "  - console: tgm"] if first else []),
        f"  - console: {{line: cow ARG_Province {cx} {cy}, settle: 60}}", "  - wait: 8",
        "  - console: set gamehour to 13", f"  - console: player.setpos x {x:.0f}", f"  - console: player.setpos y {y:.0f}",
        f"  - console: player.setpos z {z:.0f}", "  - wait: 6", f"  - console: player.setangle z {h:.0f}",
        f"  - console: player.setangle x {p:.0f}", "  - wait: 4",
        "  expect:", f"  - {{read: [player], path: pos, keep: {name}}}",
        "  reader: [the header checklist for this kind of stop]"]) + "\n"


def _stand(b: Build, subj, d_m: float, first_bearing: float, log: list, name: str):
    f = place(b, subj, d_m * U, around(first_bearing))
    x, y = f["x"], f["y"]
    h, p = aim(eye_of(b, x, y), subj)
    log.append({"journey": "river-steps" if name else "", "step": name, "moved_m": f["moved_m"], "why": f["why"],
                "clear": f["clear"]})
    return x, y, b.ground_u(x, y) + SEAT_U, h, p


def river_steps(b: Build, w, log: list) -> str:
    from tools.argonia_world.water import layer
    steps = w.query("SELECT cx, cy, edge, upper_m, lower_m, cross_lo, cross_hi FROM water_step WHERE chain != 'closed' "
                    "ORDER BY upper_m - lower_m DESC, cx, cy, edge LIMIT 3")
    out, first = [RIVER_HEAD], True
    for n, s in enumerate(steps, 1):
        x0, y0, into = _edge_mid(s["cx"], s["cy"], s["edge"], s["cross_lo"], s["cross_hi"])
        subj = (x0, y0, (s["lower_m"] + s["upper_m"]) / 2 * U)
        # the foot of the step seen from the lower water's bank: across the flow first, then down it
        x, y, z, h, p = _stand(b, subj, STEP_STAND_M, into + 60, log, f"step-{n}")
        out.append(_cow_step(f"step-{n}", f"kept {s['upper_m'] - s['lower_m']:.1f} m step ({s['cx']},{s['cy']}) "
                             f"{s['edge']}", x, y, z, h, p, subj, first))
        first = False
    # three dry gullies from the build's dry reaches (cell_kind 'dry'): each at its centreline's middle cell, the
    # chosen ones (GULLIES) first, the first three whose bed takes a dry, clear stand
    pts = {}
    for rid, e, so in w.query("SELECT p.reach_id, p.east_m, p.south_m FROM hydrology_reach_point p JOIN hydrology_reach r "
                              "ON r.id = p.reach_id WHERE r.cell_kind = 'dry' ORDER BY p.reach_id, p.ord"):
        pts.setdefault(rid, []).append((e, so))
    order = [g[1] for g in GULLIES if g[1] in pts] + sorted(r for r in pts if r not in {g[1] for g in GULLIES})
    kept, spare = [], []
    for reach in order:
        cx, cy = su.cell_of(*su.province_to_skyrim(*pts[reach][len(pts[reach]) // 2]))
        subj = _cell_low(b, cx, cy)
        f = place(b, subj, BED_STAND_M * U, around(0.0))
        (kept if f["clear"] else spare).append((reach, cx, cy, subj))
        if len(kept) == 3:
            break
    for n, (reach, cx, cy, subj) in enumerate((kept + spare)[:3], 1):
        x, y, z, h, p = _stand(b, subj, BED_STAND_M, 0.0, log, f"gully-{n}")
        out.append(_cow_step(f"gully-{n}", f"dry gully {reach}, its bed in cell ({cx},{cy})", x, y, z, h, p, subj, first))
    for name, (cx, cy) in STILLS:  # still a still body's cell (a lake, tarn or marsh: no flow) in this build
        kind = w.query("SELECT b.kind FROM cell_water c JOIN hydrology_body b ON b.id = c.body_id WHERE c.cx = ? AND c.cy = ?",
                       cx, cy)
        assert kind and kind[0][0] in layer.STILL_KINDS, (cx, cy)
        subj = _cell_low(b, cx, cy, wet=True)
        x, y, z, h, p = _stand(b, subj, BED_STAND_M, 0.0, log, name)
        out.append(_cow_step(name, f"still water in cell ({cx},{cy}), level {su.units_to_metres(subj[2]):.1f} m",
                             x, y, z, h, p, subj, first))
    return "".join(out)


# -- road-look ---------------------------------------------------------------------------------------------------------
ROAD = "route.road.gideon-blackwood-road"
ROAD_AT = (("blackwood-20", 0.20), ("blackwood-flat-46", 0.46), ("blackwood-slope-57", 0.57))
ROAD_AHEAD_M = 25.0


def _along(pts: list[tuple[float, float]], f: float) -> tuple[float, float, int]:
    seg = [math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(pts, pts[1:])]
    want, acc = f * sum(seg), 0.0
    for i, s in enumerate(seg):
        if acc + s >= want:
            t = (want - acc) / s if s else 0.0
            return pts[i][0] + t * (pts[i + 1][0] - pts[i][0]), pts[i][1] + t * (pts[i + 1][1] - pts[i][1]), i
        acc += s
    return pts[-1][0], pts[-1][1], len(pts) - 2


def road_look(b: Build, w, log: list) -> str:
    path = JOURNEYS / "road-look.yaml"
    head = [ln for ln in path.read_text().splitlines() if ln.startswith("#")]
    pts = [su.province_to_skyrim(r["x_m"], r["y_m"]) for r in w.query(
        "SELECT x_m, y_m FROM road_point WHERE route_id = ? ORDER BY ord", ROAD)]
    total = sum(math.hypot(q[0] - p[0], q[1] - p[1]) for p, q in zip(pts, pts[1:]))
    lines = head + ["id: road-look", "runner: 1", "crash_risk: low", "scene: claywater", "steps:",
                    "  - name: road-in", "    expect: [{console: \"player.GetInWorldspace ARG_Province\", contains: \">> 1\"}]"]
    for k, (name, f) in enumerate(ROAD_AT):
        ahead = ROAD_AHEAD_M * U / total
        sx, sy, _ = _along(pts, min(f + ahead, 1.0))
        subj = (sx, sy, b.ground_u(sx, sy) + 0.5 * U)  # the road's surface 25 m on, looking along it
        px, py, _ = _along(pts, f)  # down the road first; off it to either side when that line is wet or leafy
        f0 = place(b, subj, ROAD_AHEAD_M * U, around(math.degrees(math.atan2(px - sx, py - sy)) % 360))
        x, y = f0["x"], f0["y"]
        h, p = aim(eye_of(b, x, y), subj)
        log.append({"journey": "road-look", "step": name, "moved_m": f0["moved_m"], "why": f0["why"], "clear": f0["clear"]})
        lines += [f"  - name: {name}", f"    # subject: {subj[0]:.0f} {subj[1]:.0f} {subj[2]:.0f}",
                  f"    do: [{{console: \"player.setpos x {x:.0f}\"}}, {{console: \"player.setpos y {y:.0f}\"}}, "
                  f"{{console: \"player.setpos z {b.ground_u(x, y) + SEAT_U:.0f}\"}},",
                  f"         {{console: \"player.setangle z {h:.0f}\"}}, {{console: \"player.setangle x {p:.0f}\"}}, {{wait: 4}}]"]
        if k == len(ROAD_AT) - 1:
            lines.append("    expect: [{console: \"player.GetInWorldspace ARG_Province\", contains: \">> 1\"}]")
    return "\n".join(lines) + "\n"


# -- the Claywater vantages ----------------------------------------------------------------------------------------------
CLAY_STAND_M = {"person": 3.5, "thing": 8.0}
MOVE = re.compile(r'\{console: "player\.moveto (ARG_Ref_\w+)(?: -?\d+){3}"\}, \{console: "player\.setangle z -?\d+"\}'
                  r'|\{console: "player\.moveto (ARG_Ref_\w+)"\}')


def claywater(b: Build, name: str, log: list) -> str:
    """Each moveto onto a ground-placed ref becomes a moveto beside it (dx dy dz off the ref) on dry ground with a
    clear eye line, facing it; refs with their own z (doors on porches) and hand offsets stay."""
    path = JOURNEYS / f"{name}.yaml"
    lines = path.read_text().splitlines()
    for i, ln in enumerate(lines):
        def sub(m):
            edid = m.group(1) or m.group(2)
            r = b.ref(edid)
            if r is None or r.get("interior") or r["own_z"]:
                return m.group(0)
            person = "Livia" in edid or "Signs" in edid or "Gaius" in edid or "Takes" in edid
            rz = b.water_u(r["x"], r["y"]) if b.wet(r["x"], r["y"]) else b.ground_u(r["x"], r["y"])
            subj = (r["x"], r["y"], rz + (1.0 if person else 0.5) * U)
            f = place(b, subj, CLAY_STAND_M["person" if person else "thing"] * U, around(180.0))
            x, y = f["x"], f["y"]
            h, _ = aim(eye_of(b, x, y), subj)
            log.append({"journey": name, "step": edid, "moved_m": f["moved_m"], "why": f["why"], "clear": f["clear"]})
            dz = b.ground_u(x, y) + SEAT_U - rz
            return (f'{{console: "player.moveto {edid} {x - r["x"]:.0f} {y - r["y"]:.0f} {dz:.0f}"}}, '
                    f'{{console: "player.setangle z {h:.0f}"}}')
        if "player.moveto" in ln:
            lines[i] = MOVE.sub(sub, ln)
    return "\n".join(lines) + "\n"


