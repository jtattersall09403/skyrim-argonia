            same = sum(cls.get((cx + i_, cy + j_)) == c for i_ in range(-2, 3) for j_ in range(-2, 3))
            if len(P) and (np.hypot(P[:, 0] - r["x"], P[:, 1] - r["y"]) < 3 * su.CELL_UNITS + P[:, 2] * U).any():
                continue
            if b.wet(r["x"], r["y"]):
                continue
            d = np.hypot(xy[:, 0] - r["x"], xy[:, 1] - r["y"])
            n = int((d < reach).sum())
