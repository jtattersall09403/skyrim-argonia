def _wet_near(b: Build, pt: tuple, reach_m: float = FIT_WET_M):
    """The wet point nearest pt (2 m grid) within reach_m, or None."""
    n = int(reach_m / SAMPLE_M)
    for i, j in sorted(((i, j) for i in range(-n, n + 1) for j in range(-n, n + 1)), key=lambda c: c[0] ** 2 + c[1] ** 2):
        if math.hypot(i, j) > n:
            break
        x, y = pt[0] + i * SAMPLE_M * U, pt[1] + j * SAMPLE_M * U
        if b.wet(x, y):
            return x, y, b.water_u(x, y)
    return None


def _first_wet(b: Build, pt: tuple, ux: float, uy: float, limit_m: float = 400.0):
    """From pt, walk (ux, uy) to the first wet sample (pt itself if wet): the real shore of a water cell dry at its middle."""
    for k in range(int(limit_m / SAMPLE_M)):
        px, py = pt[0] + ux * k * SAMPLE_M * U, pt[1] + uy * k * SAMPLE_M * U
        if b.wet(px, py):
            return px, py, b.water_u(px, py)
    return None


STANDS: list = []   # (name, x, y, heading, pitch, clearance3, frame share, near share) of the last refresh
CLEAR_STOPS = ("sea", "river", "brackish-rim")   # round 5: these read clear and stood under canopy, in fronds


FIT_FAR_M = 600.0       # past FIT_REACH_M the search widens to 600 m
SHORT_OF_FRAME: dict[str, str] = {}      # the stops no stand within FIT_FAR_M meets the frame share for (the report's)


def _grid(step_m: float, lo_m: float, hi_m: float, at=(0.0, 0.0)):
    k = int(hi_m / step_m)
    pts = [(at[0] + i * step_m, at[1] + j * step_m) for i in range(-k, k + 1) for j in range(-k, k + 1)
           if lo_m <= math.hypot(i, j) * step_m <= hi_m]
    return sorted(pts, key=lambda c: c[0] ** 2 + c[1] ** 2)


FIT_STRICT_STEP_M = 4.0    # every shore's near field on a 4 m grid (strict), then the best shore's widened search:
FIT_COARSE_M, FIT_FINE_M = 25.0, 2.5   # 25 m to FIT_FAR_M, then 2.5 m within 25 m of the coarse best


def _fit(b: Build, name: str, f: dict, centre: tuple, sea: bool, log: list, strict: bool = False):
    """The authored stand `f` aimed at the body's centre, or the nearest stand that is dry footing, whose aim point is
    water, whose clearance reads 0/0/0 (placed plants on the eye line, canopy over the eye, tall landscape grass near the
    eye and under the first 20 m of the line) and whose frame share (the lower half of the still, 0-60 m, +-30 deg, from
    the eye's height and pitch over the ground and water heights) is at least FRAME_MIN_SHARE. `strict` searches
    FIT_REACH_M on a 4 m grid and raises when none; else a 2 m grid to FIT_REACH_M, a 25 m grid to FIT_FAR_M and a 2.5 m
    grid round the best, which is kept (meeting the share first, then fewest hits) and named in SHORT_OF_FRAME when
    short. Returns (x, y, subject, share)."""
    w_ = None if sea else _wet_near(b, centre)

    def ev(di, dj):
        x, y = f["x"] + di * U, f["y"] + dj * U
        if b.soaked(x, y):
            return None
        if sea:   # the aim 400 m out over water, the horizon in frame
            brg = math.atan2(centre[0] - x, centre[1] - y)
            px, py = x + math.sin(brg) * SEA_OUT_M * U, y + math.cos(brg) * SEA_OUT_M * U
            subj = (px, py, b.water_u(px, py) or 0.0)
        else:
            subj = w_ and (w_[0], w_[1], w_[2])
        if not subj or not b.wet(subj[0], subj[1]):
            return None
        eye = eye_of(b, x, y)
        h, p = aim(eye, subj)
        if sea:
            subj, p = (subj[0], subj[1], eye[2]), 0.0
        if stand_bad(b, x, y, (eye[0] + math.sin(math.radians(h)) * 60 * U, eye[1] + math.cos(math.radians(h)) * 60 * U, eye[2])):
            return None
        cl = sum(clearance(b, eye, h))
        if strict and cl:
            return None
        cl += grass_hits(b, eye, h, first=strict)
        if strict and cl:
            return None
        sh = frame_share(b, x, y, h, p)
        return ((sh < FRAME_MIN_SHARE, cl, -sh), di, dj, x, y, subj, sh)

    best = None

    def run(cands):
        nonlocal best
        for di, dj in cands:
            r = ev(di, dj)
            if r and (best is None or r[0] < best[0]):
                best = r
            if best and best[0][:2] == (False, 0):
                return True
        return False

    if strict:
        run(_grid(FIT_STRICT_STEP_M, 0.0, FIT_REACH_M))
    elif not run(_grid(SAMPLE_M, 0.0, FIT_REACH_M)) and not run(_grid(FIT_COARSE_M, FIT_REACH_M, FIT_FAR_M)) and best:
        run(_grid(FIT_FINE_M, 0.0, FIT_COARSE_M, at=(best[1], best[2])))
    if best is None:
        raise ValueError(f"water-types: {name}: no dry stand with a water aim within {FIT_FAR_M:.0f} m of "
                         f"({f['x']:.0f}, {f['y']:.0f})")
    (_, cl, nsh), di, dj, x, y, subj, sh = best
    if strict and sh < FRAME_MIN_SHARE:
        raise ValueError(f"water-types: {name}: no clear stand within {FIT_FAR_M:.0f} m holds {FRAME_MIN_SHARE:.0%} "
                         f"water in the lower frame (best {sh:.0%})")
    if cl or sh < FRAME_MIN_SHARE:
        SHORT_OF_FRAME[name] = f"best stand: {cl} clearance hits, frame share {sh:.0%}"
        print(f"water-types: WARNING {name}: {SHORT_OF_FRAME[name]}")
    log.append({"journey": "water-types", "step": name, "moved_m": round(math.hypot(di, dj), 1),
                "why": "re-aimed at the body's centre", "clear": cl == 0})
    return x, y, subj, sh


def _stop_at(b: Build, name: str, cx: int, cy: int, dx: int, dy: int, level: dict, line: dict, reach_of: dict, log: list,
             strict: bool = False):
    """One water stop at a shore cell (cx, cy), its dry side (dx, dy): the stand fitted to hold water (_fit)."""
    ox, oy = su.cell_origin(cx, cy)
    z = su.metres_to_units(level[(cx, cy)])
    f = None
    if name in ("river", "stream"):
        pts = line[reach_of[(cx, cy)]]
        mid = min(range(len(pts) - 1), key=lambda i: math.hypot(pts[i][0] - ox - su.CELL_UNITS / 2, pts[i][1] - oy - su.CELL_UNITS / 2))
        ahead = min(len(pts) - 1, mid + int(DOWNSTREAM_M / 5.5))
        tx, ty = pts[ahead][0] - pts[mid][0], pts[ahead][1] - pts[mid][1]
        n = math.hypot(tx, ty) or 1.0
        for side in (1, -1):  # the bank to the reach's left, then right, standing back upstream of the subject
            nx, ny = -ty / n * side, tx / n * side
            f = _water_stop(b, name, (pts[mid][0], pts[mid][1], z), nx, ny, log)
            if f:
                # face downstream: the subject moves down the reach, the stand stays on the bank
                subj = (pts[ahead][0], pts[ahead][1], z)
                break
    else:
        dist = SEA_OUT_M * U if name == "sea" else REACH_CELLS / 2 * su.CELL_UNITS
        sx = ox + su.CELL_UNITS / 2 - dx * dist
        sy = oy + su.CELL_UNITS / 2 - dy * dist
        subj = (sx, sy, z)
        near = (ox + su.CELL_UNITS / 2, oy + su.CELL_UNITS / 2, z)
        near = _first_wet(b, near, -dx, -dy) or _cell_low(b, cx, cy, wet=True)
        f = _water_stop(b, name, near, dx, dy, log)
        if f:   # the body's centre: from the shore point out over the water (the sea: 400 m, the horizon in frame)
            sh = _shore(b, near[0], near[1], dx, dy) or near
            subj = (sh[0] - dx * (SEA_OUT_M if name == "sea" else REACH_CELLS / 2 * su.CELL_UNITS / U) * U,
                    sh[1] - dy * (SEA_OUT_M if name == "sea" else REACH_CELLS / 2 * su.CELL_UNITS / U) * U, z)
    if not f:
        raise ValueError(f"water-types: {name}: no dry stand by cell ({cx},{cy})")
    return _fit(b, name, f, subj, name == "sea", log, strict)


def water_types(b: Build, w, log: list) -> str:
    from tools.argonia_world.water.__main__ import cell_types
    cells = cell_types(w)
    types = {k: t for k, (_, t) in cells.items()}
    level = {k: v for k, (v, _) in cells.items()}
    reach_of = {(r[0], r[1]): r[2] for r in w.query("SELECT cx, cy, reach_id FROM cell_water WHERE reach_id IS NOT NULL")}
    line = {}
    for rid, e, so in w.query("SELECT reach_id, east_m, south_m FROM hydrology_reach_point ORDER BY reach_id, ord"):
        line.setdefault(rid, []).append(su.province_to_skyrim(e, so))
    dirs = ((1, 0), (-1, 0), (0, 1), (0, -1))
    x0, y0 = su.PROVINCE_CELL_SW
    inside = lambda x, y: x0 + 1 <= x < x0 + su.PROVINCE_CELLS - 1 and y0 + 1 <= y < y0 + su.PROVINCE_CELLS - 1  # noqa: E731
    out, first = [WATER_TYPES_HEAD], True
    STANDS.clear()
    SHORT_OF_FRAME.clear()
    for name, want in WATER_TYPE_STOPS:
        cands_ = []
        for (cx, cy), t in sorted(types.items()):
            if t not in want:
                continue
            for dx, dy in dirs:
                if (cx + dx, cy + dy) in types or not inside(cx + dx, cy + dy):
                    continue  # (dx, dy) is the dry side, in the province; the water lies the other way
                if name in ("river", "stream"):
                    pts = line.get(reach_of.get((cx, cy)), [])
                    score = len(pts) if len(pts) > 12 else 0
                else:
                    score = sum(1 for k in range(1, REACH_CELLS + 1) if types.get((cx - dx * k, cy - dy * k)) in want)
                if score:
                    cands_.append((score, (cx, cy), (dx, dy)))
        if not cands_:
            raise ValueError(f"water-types: no shore cell of {want}")
        cands_.sort(key=lambda c: -c[0])   # the best shore first; a shore with no stand holding water goes to the next
        err, got = None, None
        # every stop takes the first shore whose stand reads 0/0/0 with the frame share; none: the widened search, warned
        for strict in (True, False):
            print(f"water-types: {name}: {'strict' if strict else 'widened'} search over {min(len(cands_), FIT_SHORES)} shores", flush=True)
            for _, (cx, cy), (dx, dy) in cands_[:FIT_SHORES]:
                n_log = len(log)
                try:
                    got = _stop_at(b, name, cx, cy, dx, dy, level, line, reach_of, log, strict)
                except ValueError as e:
                    err = err or e
                    del log[n_log:]
                    continue
                break
            if got:
                break
            print(f"water-types: WARNING {name}: no shore of {len(cands_)} has a stand clear of fronds and canopy")
        if not got:
            raise ValueError(f"{err} (and {min(len(cands_), FIT_SHORES) - 1} other shores)")
        x, y, subj, share = got
        h, p = aim(eye_of(b, x, y), subj)
        if name == "sea":
            p = 0.0
        cl = clearance3(b, eye_of(b, x, y), h)
        fs = frame_share(b, x, y, h, p)
        STANDS.append((name, x, y, h, p, cl, fs, share))
        print(f"water-types: {name}: clearance {cl[0]}/{cl[1]}/{cl[2]} (plants on the eye line / canopy / tall grass); "
              f"frame share {fs:.0%} (lower half, 0-60 m, +-30 deg; needs {FRAME_MIN_SHARE:.0%}); "
              f"near-field share {water_share(b, x, y, h):.0%} at {x:.0f} {y:.0f} facing {h:.0f} pitch {p:.0f}")
        if name == "sea":
            p = 0.0
        out.append(_cow_step(name, f"{types[(cx, cy)]} water from cell ({cx},{cy}), level {level[(cx, cy)]:.1f} m",
                             x, y, b.ground_u(x, y) + SEAT_U, h, p, subj, first))
        first = False
    return "".join(out)


