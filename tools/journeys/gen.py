def _stand(b: Build, subj, d_m: float, first_bearing: float, log: list, name: str):
    f = place(b, subj, d_m * U, around(first_bearing))
    x, y = f["x"], f["y"]
    h, p = aim(eye_of(b, x, y), subj)
    log.append({"journey": "river-steps" if name else "", "step": name, "moved_m": f["moved_m"], "why": f["why"],
                "clear": f["clear"]})
    return x, y, b.ground_u(x, y) + SEAT_U, h, p


STEP_BAND_M = (15, 25)     # a step's stand: from the side of the step, 15-25 m from its crossing's middle
STEP_SIDE_DEG = (0, 15, -15, 30, -30, 45, -45)   # off the perpendicular to the flow, both banks
STEP_MIN_SHARE = 0.6       # the step's pieces (upper and lower water along the crossing) in sight and inside the frame
STEP_FRAME_DEG = (35.0, 28.0)   # half the frame across, half up/down: the pieces lie in it with the drop at its middle


def _seen(b: Build, eye: tuple, pt: tuple, n: int = 12) -> bool:
    """The ground does not rise over the line from the eye to pt (the last 1 m excepted: the point's own bank)."""
    L = math.hypot(pt[0] - eye[0], pt[1] - eye[1]) or 1.0
    for k in range(1, n):
        t = k / n
        if t * L > L - 2 * U:
            break
        if b.ground_u(eye[0] + (pt[0] - eye[0]) * t, eye[1] + (pt[1] - eye[1]) * t) > eye[2] + (pt[2] - eye[2]) * t:
            return False
    return True


def step_pieces(b: Build, s, x0: float, y0: float, into: float) -> list[tuple]:
    """Points on the step's pieces along the crossing: the rapids line on the upper water at the edge, and the foot (skirt
    and ring) on the lower water where it first lies over the ground walking down the flow (up to 40 m)."""
    a = math.radians(into)
    fx, fy = math.sin(a), math.cos(a)            # into the lower cell
    ax, ay = (1.0, 0.0) if s["edge"] in ("n", "s") else (0.0, 1.0)   # along the edge
    half = (s["cross_hi"] - s["cross_lo"]) / 2 * su.VERTEX_SPACING_UNITS
    up, lo = s["upper_m"] * U, s["lower_m"] * U
    out = []
    for k in range(5):
        o = (k / 4 - 0.5) * 2 * half
        ex, ey = x0 + ax * o, y0 + ay * o
        out.append((ex, ey, up))
        for m in range(1, 41):
            px, py = ex + fx * m * U, ey + fy * m * U
            if b.ground_u(px, py) < lo:
                out.append((px, py, lo))
                break
    return out


def step_share(b: Build, eye: tuple, h: float, p: float, pieces: list[tuple]) -> float:
    """The share of the step's piece points in sight from the eye and inside the frame (STEP_FRAME_DEG of the aim)."""
    n = 0
    for pt in pieces:
        ph, pp = aim(eye, pt)
        dh = (ph - h + 180) % 360 - 180
        if abs(dh) <= STEP_FRAME_DEG[0] and abs(pp - p) <= STEP_FRAME_DEG[1] and _seen(b, eye, pt):
            n += 1
    return n / len(pieces)


def step_stand(b: Build, s, x0: float, y0: float, into: float, subj: tuple):
    """The stand from the side of the step (perpendicular to the flow, either bank, then up to 45 deg off), STEP_BAND_M
    from its middle, on dry footing, its eye ray free, its clearance 0/0/0 and the most of its pieces in frame; the first
    meeting STEP_MIN_SHARE, else the best (returned with ok False). Returns (x, y, h, p, clearance3, share, ok)."""
    pieces = step_pieces(b, s, x0, y0, into)
    best = None
    for off in STEP_SIDE_DEG:
        for side in (90, -90):
            brg = math.radians(into + side + off)
            for d in sorted(range(STEP_BAND_M[0], STEP_BAND_M[1] + 1), key=lambda v: abs(v - 20)):
                x, y = x0 + math.sin(brg) * d * U, y0 + math.cos(brg) * d * U
                if b.soaked(x, y):
                    continue
                eye = eye_of(b, x, y)
                h, p = aim(eye, subj)
                if stand_bad(b, x, y, subj):
                    continue
                cl = clearance3(b, eye, h)
                sh = step_share(b, eye, h, p, pieces)
                if best is not None and best[0][0] is False and sh < STEP_MIN_SHARE:
                    continue
                fc = frustum_cover(b, eye, h, p)
                key = (sh < STEP_MIN_SHARE, not cover_ok(fc), sum(cl), abs(p) // 10, -sh)
                if best is None or key < best[0]:
                    best = (key, (x, y, h, p, cl, sh, fc))
                if sum(cl) == 0 and sh >= STEP_MIN_SHARE and cover_ok(fc):
                    return x, y, h, p, cl, sh, fc, True
    if best is None:
        raise ValueError(f"river-steps: no dry stand {STEP_BAND_M} m from the step at ({x0:.0f}, {y0:.0f})")
    return (*best[1], False)


